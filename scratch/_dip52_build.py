def api(doi):
    url = "https://api.openalex.org/works/https://doi.org/" + doi + "?api_key=" + KEY
    req = urllib.request.Request(url, headers={"User-Agent": "dip52 (mailto:dip@marfagenez.local)"})
    with urllib.request.urlopen(req, timeout=90) as r:
        return json.load(r)


def recon(inv):
    if not inv:
        return ""
    pos = {}
    for tok, idxs in inv.items():
        for i in idxs:
            pos[i] = tok
    return " ".join(pos[i] for i in sorted(pos))


def norm(t):
    t = t.replace("-\n", "").replace("\u2010\n", "").replace("\u00ad", "")
    t = t.replace("\u2019", "'").replace("\u2018", "'")
    t = re.sub(r"[ \t\u00a0]+", " ", t)
    return t


def load(name):
    p = TXT / name
    if not p.exists():
        return None
    return norm(p.read_text(encoding="utf-8", errors="replace"))


