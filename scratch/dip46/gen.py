def rx(anchor):
    parts = [re.escape(p) for p in anchor.split()]
    return re.compile(r'\s+'.join(parts))

def clean(q):
    q = q.replace('\u2009', ' ').replace('\xa0', ' ')
    q = re.sub(r'\s+', ' ', q).strip()
    q = re.sub(r'\s+([,.;:)])', r'\1', q)
    return q

def extract(t, span):
    if isinstance(span, str):
        return span
    a, b = span
    m = rx(a).search(t)
    if not m:
        raise SystemExit('anchor not found: ' + a)
    m2 = rx(b).search(t, m.end() - 1)
    if not m2:
        raise SystemExit('end anchor not found: ' + b)
    return clean(t[m.start():m2.end()])

def build():
    recs, fails = [], []
    for a in ATOMS:
        t = src(a['pmc'])
        nt = norm(t)
        works = []
        for loc, span in a['quotes']:
            q = extract(t, span)
            if norm(q) not in nt:
                fails.append((a['id'], q[:90]))
            works.append({'doi': a['doi'], 'locator': loc, 'access': 'fulltext', 'quote': q})
            print('%-11s %-4s %2d words  %s' % (a['id'], 'OK' if norm(q) in nt else 'BAD',
                                                len(q.split()), q[:70]))
        recs.append({
            'atom': a['id'], 'statement': a['statement'], 'domain': 'bio.integration',
            'kind': a['kind'], 'mechanism': a['mechanism'], 'formula': a['formula'],
            'symbols': a['symbols'], 'conditions': a['conditions'], 'works': works,
            'confidence': 'medium', 'locator_status': 'verified', 'tags': a['tags'], 'notes': a['notes'],
        })
    return recs, fails

if __name__ == '__main__':
    recs, fails = build()
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, 'dip-2026-11-23-46.jsonl')
    with open(path, 'w', encoding='utf-8') as f:
        for r in recs:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
    print('\nwrote', path, len(recs), 'records')
    print('FAILS', fails)
