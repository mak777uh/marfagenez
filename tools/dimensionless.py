"""Пороги безразмерных чисел: совпадают они или зависят от геометрии?

Числа — из принятых ячеек. Скрипт только собирает пороги и показывает, равны ли они единице.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "DIMENSIONLESS.md"

# (число, определение, порог перехода, что переключается, ячейка)
NUMBERS = [
    ("Дамкёлер Da", "скорость реакции / скорость переноса", "1", "транспорт → реакция", "DIP53-0002"),
    ("Дамкёлер Da (фибрин)", "то же", "2,3 и 355", "умеренное преобладание → быстрое осаждение", "DIP53-0001"),
    ("Пекле Pe", "адвекция / диффузия", "1", "диффузия → адвекция", "DIP53-0002"),
    ("Пекле Pe (микрочастицы)", "то же", "≈1000", "адвекция резко доминирует", "DIP53-0003"),
    ("Пекле Pe (антитело)", "то же", "3,3·10⁻²", "адвекция отброшена", "DIP53-0005"),
    ("Дина De", "время релаксации / время течения", "1", "ньютоновский предел", "DIP53-0006"),
    ("модуль Тиле φ", "реакция / диффузия в поре", "2,82 и 4,78", "исчерпание субстрата, гипоксия", "DIP53-0009"),
    ("Тилле (катализ)", "то же", "0,4 и 4", "кинетика → смешанный → диффузия", "DIP51-0008"),
    ("Био Bi", "внутреннее сопротивление / внешнее", "1/6", "однородная температура → градиент", "DIP53-0011"),
    ("Шервуд Sh", "массоперенос / диффузия", "5,10–7,10", "диффузионный контроль", "DIP53-0012"),
]


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Пороги безразмерных чисел: совпадают или нет")
    a("")
    a("Сгенерировано `tools/dimensionless.py` по принятым ячейкам. Проверяется один вопрос: "
      "**переход происходит при единице или при другом числе?**")
    a("")
    a("| число | определение | порог | что переключается | ячейка |")
    a("|---|---|---|---|---|")
    for name, defn, thr, what, cell in NUMBERS:
        a(f"| {name} | {defn} | **{thr}** | {what} | `{cell}` |")
    a("")
    a("## Что видно")
    a("")
    a("1. **Большинство порогов — единица.** Дамкёлер, Пекле, Дина переключают режим при переходе "
      "через 1. Это не совпадение: все три по построению сравнивают два времени или две скорости, "
      "и равенство наступает, когда они равны.")
    a("2. **Но два порога не единица.** У Био переход при **1/6**, а не при 1; у Шервуда порог задан "
      "не константой, а корреляцией (Sh от Sc в степени 0,33).")
    a("3. **Значит ось общая, а конкретное число перехода зависит от геометрии.** У Био 1/6 возникает "
      "из решения для сферы: критерий однородности температуры в шаре не равен критерию в пластине.")
    a("")
    a("## Вывод для формулы")
    a("")
    a("Формула не может иметь один универсальный порог `v*`. Она должна иметь **безразмерное отношение** "
      "и **порог, зависящий от геометрии**, — как у Био. Это объясняет, почему в разных системах мы "
      "видели пороги 12,1 мМ/мин, 187 °C/мин, 1·10⁻⁵ 1/с и 5 МПа: они просто в разных единицах и с "
      "разной геометрией.")
    a("")
    a("## Чего не хватает")
    a("")
    a("- **Дамкёлер для ткани или эмбриона** — не найден;")
    a("- **Пекле для морфогена** — не найден;")
    a("- **Дина для крови и слизи** — не найден (есть только для сперматозоидов и водорослей);")
    a("- **число Кнудсена в биологии** — не найдено (46 открытых текстов, все аэрозоли и мембраны).")
    a("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
