def main(argv: list[str]) -> int:
    atoms = [json.loads(l) for l in (ROOT / "literature" / "map" / "atoms.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    lit = json.loads((ROOT / "kg" / "lit-refs.json").read_text(encoding="utf-8"))["map"]

    rows = []
    for a in atoms:
        refs = a.get("kg_ref") or []
        if not refs:
            continue
        feat, verdict = KIND.get(a["atom"], ("не задан", "не задан"))
        rows.append((a["atom"], a["domain"], ", ".join(refs), feat, verdict))
    rows.sort()

    lines: list[str] = []
    p = lines.append
    p("# Таблица сшивки: что с чем сравнимо")
    p("")
    p("Сгенерировано `tools/stitch_table.py` по полю `kg_ref` в литературной карте и `kg/lit-refs.json`. "
      "Признак сравнимости задан вручную: скрипт не выводит его из текста.")
    p("")
    p(f"Пар: **{len(rows)}**; узлов `kg/` в сшивке: **{len(lit)}**.")
    p("")
    p("| ячейка | область | узлы `kg/` | признак | сравнимо? |")
    p("|---|---|---|---|---|")
    for cell, dom, refs, feat, verdict in rows:
        p(f"| {cell} | {dom} | {refs} | {feat} | {verdict} |")
    p("")
    cnt = collections.Counter(r[4].split(":")[0] for r in rows)
    p("## Сколько с чем")
    p("")
    for k, v in cnt.most_common():
        p(f"- **{k}**: {v}")
    p("")
    p("## Что видно")
    p("")
    p("1. **Сшивка идёт по безразмерному и по порогам**, а не по абсолютным скоростям: это ровно вывод")
    p("   `docs/COLLAPSE.md` — ось общая там, где отношение.")
    p("2. **Одна пара прямо несравнима:** `B24-01-0003` (внутренний максимум по темпу) против `F-006`")
    p("   (складка Chao). Это и есть содержание `GAP-02` в таблице.")
    p("3. **Четыре пары частичные:** совпадает признак, но объект или форма другие. Их нельзя записывать")
    p("   как подтверждение, только как «рядом лежит».")
    p("")
    p("## Чего таблица не даёт")
    p("")
    p("- **Ни одна пара не проверена экспериментом.** Сшивка говорит «эти величины измеримы вместе»,")
    p("   а не «они равны».")
    p("- Признак сравнимости — моя классификация; её можно оспорить, и это нормально.")

    text = "\n".join(lines) + "\n"
    print(text[:1500])
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"\nзаписано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
