"""Проверка ребра `B7-09-0001 --refines--> B7-03-0002`: одна ли это величина?

Утверждение, которое я поставил в карту: «стоимость построения кутикулы 1,58–2,67 г глюкозы/г при
2,95–27,4 г/м² уточняет стоимость липидного слоя 0,12 Дж/м² — та же величина в разных единицах».

Проверяем переводом обеих величин в Дж/м².

Источники чисел:
  B7-09-0001: масса кутикулы 2,95–27,4 г/м²; стоимость 1,58–2,67 г глюкозы на грамм кутикулы.
  B7-03-0002: 0,12 пДж/мкм² = 0,12 Дж/м².

Энергия глюкозы при сгорании ≈ 15,6 кДж/г (2803 кДж/моль ÷ 180,156 г/моль).

Опровергающее условие: если величины отличаются больше чем на порядок, это НЕ одна величина, и тип
связи `refines` неверен; допустим только `analogous` с оговоркой о масштабе.

Запуск: python3 tools/cuticle_cost.py
"""

from __future__ import annotations

GLUCOSE_KJ_PER_G = 2803.0 / 180.156   # удельная энергия глюкозы, кДж/г


def main() -> int:
    print(f"энергия глюкозы: {GLUCOSE_KJ_PER_G:.2f} кДж/г")
    print()

    # кутикула: г глюкозы/г × г/м² = г глюкозы/м²
    mass = (2.95, 27.4)          # г/м²
    cost_per_g = (1.58, 2.67)    # г глюкозы на грамм кутикулы
    glu_per_m2 = (mass[0] * cost_per_g[0], mass[1] * cost_per_g[1])
    j_per_m2 = tuple(g * GLUCOSE_KJ_PER_G * 1000 for g in glu_per_m2)
    print("кутикула (B7-09-0001):")
    print(f"  масса {mass[0]}–{mass[1]} г/м², стоимость {cost_per_g[0]}–{cost_per_g[1]} г глюкозы/г")
    print(f"  → {glu_per_m2[0]:.2f}–{glu_per_m2[1]:.2f} г глюкозы/м²")
    print(f"  → {j_per_m2[0]:,.0f}–{j_per_m2[1]:,.0f} Дж/м²")
    print()

    lipid = 0.12  # Дж/м² (0,12 пДж/мкм²)
    print("липидный слой мембраны (B7-03-0002):")
    print(f"  0,12 пДж/мкм² = {lipid} Дж/м²")
    print()

    lo = j_per_m2[0] / lipid
    hi = j_per_m2[1] / lipid
    print(f"отношение кутикула/мембрана: {lo:,.0f}–{hi:,.0f} раз")
    print(f"порядок: от 10^{len(str(int(lo))) - 1} до 10^{len(str(int(hi))) - 1}")
    print()

    # --- побочная проверка самой мембранной величины по порядку величины
    # Площадь липидной головы ~0,5 нм², два слоя, 1 ATP на липид = 8,3e-20 Дж (50 кДж/моль).
    atp_j = 50e3 / 6.022e23
    head_nm2 = 0.5
    lipids_per_m2 = 2 * (1e18 / head_nm2)     # два слоя
    membrane_est = lipids_per_m2 * atp_j      # Дж/м² при 1 ATP на липид
    print("проверка мембранной величины по порядку:")
    print(f"  липидов на м² (два слоя, {head_nm2} нм² на голову): {lipids_per_m2:.2e}")
    print(f"  1 ATP = {atp_j:.2e} Дж; при 1 ATP на липид: {membrane_est:.2f} Дж/м²")
    print(f"  измерено: {lipid} Дж/м² → отношение {membrane_est / lipid:.1f} "
          f"(порядок {'совпадает' if 0.1 < membrane_est / lipid < 10 else 'НЕ совпадает'})")
    print()

    same = max(lo, hi) < 10
    if same:
        print("ВЫВОД: величины одного порядка — тип `refines` допустим.")
        return 0
    print("ВЫВОД: величины различаются на", f"{hi:,.0f}", "раз — это НЕ одна величина.")
    print("        Тип связи `refines` неверен; допустимо только `analogous` с оговоркой о масштабе")
    print("        (одно понятие «цена на единицу площади», разные структуры и разные порядки).")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
