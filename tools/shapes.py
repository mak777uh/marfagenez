"""Какие формы зависимости «темп → исход» реально измерены.

Скрипт собирает опубликованные ряды (числа из принятых ячеек карты) и классифицирует их форму.
Он не подгоняет модели: только показывает, монотонен ряд, есть ли внутренний экстремум и где границы.

Источники чисел:
  B24-01-0001  Seki & Mazur 2009, Table 3 — отогрев, охлаждение 187 °C/мин
  B24-01-0002  там же — охлаждение при быстром отогреве (нулевой случай)
  B24-01-0003  там же — охлаждение при отогреве 2170 °C/мин (оптимум)
  B24-01-0005  Dumont 2004 — K562 (U-форма, числа из текста)
  B24-01-0006  Huertas 2016, Table 1 — E. coli, нагрев
  B20-01-0001  Wozny 2016 — SF2 при трёх мощностях
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "SHAPES.md"

SERIES = {
    "отогрев ооцитов (Seki, Table 3)": ([139, 476, 1220, 2170, 2950],
                                        [11.1, 54.3, 68.8, 69.4, 82.5], "%"),
    "охлаждение при отогреве 2170 (Seki)": ([37, 187, 522, 1827],
                                            [15.8, 69.4, 62.9, 30.0], "%"),
    "охлаждение при отогреве 2950 (Seki)": ([187, 522, 1827],
                                            [82.5, 88.9, 89.6], "%"),
    "K562, охлаждение (Dumont)": ([5, 180, 250, 5000, 30000],
                                  [20.0, 2.0, 2.0, 2.0, 18.0], "%"),
    "E. coli, нагрев 65 °C (Huertas, Table 1)": ([14.7, 15.4, 15.8, 17.1, 17.8],
                                                 [4.07, 3.12, 1.34, 0.31, 0.27], "log"),
    "SCC61, мощность дозы (Wozny)": ([0.5, 2.0, 10.0], [0.39, 0.24, 0.20], "SF2"),
}


def classify(xs: list[float], ys: list[float]) -> str:
    diffs = [b - a for a, b in zip(ys, ys[1:])]
    if all(d <= 0 for d in diffs):
        return "монотонно падает"
    if all(d >= 0 for d in diffs):
        return "монотонно растёт"
    imax = ys.index(max(ys))
    imin = ys.index(min(ys))
    if 0 < imax < len(ys) - 1:
        return "внутренний максимум"
    if 0 < imin < len(ys) - 1:
        return "внутренний минимум"
    return "немонотонно"


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Формы зависимости «темп → исход»: что реально измерено")
    a("")
    a("Сгенерировано `tools/shapes.py` по числам принятых ячеек карты. Ни одна модель не подгоняется:")
    a("показано, как выглядит ряд и к какому типу формы он относится.")
    a("")
    a("| ряд | скорости | исходы | форма |")
    a("|---|---|---|---|")
    rows = []
    for name, (xs, ys, unit) in SERIES.items():
        shape = classify(xs, ys)
        rows.append((name, shape))
        xs_s = " / ".join(f"{x:g}" for x in xs)
        ys_s = " / ".join(f"{y:g}" for y in ys)
        a(f"| {name} | {xs_s} | {ys_s} ({unit}) | **{shape}** |")
    a("")
    kinds: dict[str, list[str]] = {}
    for name, shape in rows:
        kinds.setdefault(shape, []).append(name)
    a("## Сколько разных форм")
    a("")
    a(f"Различных типов формы в шести рядах: **{len(kinds)}**.")
    a("")
    for shape, names in kinds.items():
        a(f"- **{shape}**: {len(names)} ({'; '.join(names)})")
    a("")
    a("## Что это значит")
    a("")
    a("1. **Единой кривой нет.** В шести рядах четыре разных типа формы: монотонный рост, монотонное")
    a("   падение, внутренний максимум и внутренний минимум.")
    a("2. **Внутренний экстремум встречается дважды** и оба раза в криобиологии, где конкурируют два")
    a("   механизма повреждения (эффекты растворов и внутриклеточный лёд).")
    a("3. **Нулевой случай** (охлаждение при быстром отогреве) показывает, что форма зависит от того,")
    a("   какой этап лимитирует: при смене лимитирующего этапа штраф за темп исчезает.")
    a("")
    a("## Чего не хватает для безразмерной оси")
    a("")
    a("Чтобы свести ряды к одной кривой `исход = f(v/v*)`, нужна критическая скорость `v*` для каждого")
    a("ряда. Она известна только там, где есть внутренний экстремум (Seki: оптимум охлаждения около")
    a("187 °C/мин) или явная граница (глиома: между 180 и 360 мОсм/(кг·ч)).")
    a("")
    a("Для монотонных рядов `v*` **не определена**: у отогрева ооцитов выживаемость растёт до самого")
    a("края диапазона, у E. coli инактивация падает до самого края. Без `v*` безразмерная ось не")
    a("строится, и сравнивать такие ряды между системами пока нельзя.")
    a("")
    a("## Практический вывод")
    a("")
    a("Формула должна содержать переключатель лимитирующего этапа, а не одну универсальную кривую:")
    a("наблюдаемые формы различаются не шумом, а тем, какой механизм первым перестаёт успевать.")
    a("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
