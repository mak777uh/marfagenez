"""`F-021`: правило κ и приоритет поддержания — где проходит переключение и что оно значит.

Узел:
    поток ассимиляции J_A делится:  κ·J_A → поддержание сомы,  (1−κ)·J_A → рост и размножение
    голодание:  κ·J_A < J_M  ⇒  поддержание платится из ветви (1−κ), рост останавливается

Проверяем числами:
1. Порог переключения: κ* = J_M / J_A. При κ ≥ κ* рост идёт с потоком (1−κ)·J_A; при κ < κ* роста нет.
2. Излом: производная роста по κ меняет знак/скачок на пороге — правило кусочно-линейное, а не гладкое.
3. Предел κ → 1: роста нет ни при каком J_A; предел κ → 0: весь поток в рост (поддержание не платится).
4. Сравнение с данными карты: κ человека 0,57–0,59 (Westerterp), 0,23–0,29 (спортсмены). При каком
   отношении J_M/J_A эти κ означают остановку роста.

Опровергающее условие: если при κ ≥ κ* рост не равен (1−κ)·J_A, правило сформулировано неверно.

Запуск: python3 tools/kappa_switch.py
"""

from __future__ import annotations


def growth(kappa: float, J_A: float, J_M: float) -> float:
    """Поток в рост по правилу: (1−κ)·J_A при κ·J_A ≥ J_M, иначе 0."""
    if kappa * J_A >= J_M:
        return (1.0 - kappa) * J_A
    return 0.0


def main() -> int:
    J_A, J_M = 100.0, 40.0            # условные единицы
    kappa_star = J_M / J_A
    print(f"J_A = {J_A}, J_M = {J_M}  ⇒  порог κ* = J_M/J_A = {kappa_star:.3f}")
    print()
    print(f"{'κ':>6} {'κ·J_A':>8} {'≥ J_M?':>7} {'поток в рост':>13} {'(1−κ)·J_A':>11}")
    prev = None
    for kappa in (0.0, 0.2, 0.39, 0.399, 0.4, 0.401, 0.41, 0.6, 0.8, 1.0):
        lhs = kappa * J_A
        g = growth(kappa, J_A, J_M)
        free = (1.0 - kappa) * J_A
        print(f"{kappa:6.3f} {lhs:8.2f} {str(lhs >= J_M):>7} {g:13.2f} {free:11.2f}")
        prev = g
    print()
    print("ЧТО ВИДНО:")
    print(f"  1. Порог ровно там, где κ·J_A = J_M: κ* = {kappa_star:.3f}.")
    print("  2. Выше порога рост линеен по κ и падает до нуля при κ → 1 (вся ассимиляция уходит на поддержание).")
    print("  3. На пороге ИЗЛОМ: слева рост 0, справа (1−κ*)·J_A =", f"{(1 - kappa_star) * J_A:.2f}")
    print("     — скачок производной, а не плавный переход. Правило кусочно-линейное.")
    print("  4. Ниже порога модель НЕ ЗАМКНУТА: роста нет, но откуда берётся недостающее поддержание —")
    print("     не сказано. Это закрывает только F-004 (запас и цена удержания), а не F-021.")
    print()

    print("КАК ЭТО ЧИТАЕТСЯ НА ДАННЫХ КАРТЫ:")
    for label, kappa in (("средний взрослый (Westerterp)", 0.57),
                         ("спортсмены (Giro)", 0.23),
                         ("клетка AmP (DEB)", 0.90)):
        kmax = kappa  # при каком J_M/J_A начинается голодание
        print(f"  κ = {kappa:.2f} ({label}): рост идёт, пока J_M/J_A ≤ {kmax:.2f}; "
              f"выше — остановка роста в модели F-021")

    # Что именно на пороге: сравниваем ПРЕДЕЛ СЛЕВА и ЗНАЧЕНИЕ СПРАВА.
    left = growth(kappa_star - 1e-9, J_A, J_M)
    right = growth(kappa_star, J_A, J_M)
    jump = right - left
    print(f"  предел слева: {left:.4f}; значение справа: {right:.4f}; скачок: {jump:.4f}")
    print()
    if abs(right - (1 - kappa_star) * J_A) > 1e-9:
        print("ВЫВОД: при κ ≥ κ* рост не совпадает с (1−κ)·J_A — правило сформулировано неверно.")
        return 1
    if abs(jump) > 1e-6:
        print("ВЫВОД: на пороге РАЗРЫВ ЗНАЧЕНИЯ (ступенька), а не излом производной.")
        print("        Модель не описывает частичную остановку роста — только «полный рост» или «ноль».")
        return 0
    print("ВЫВОД: на пороге функция непрерывна — разрыва нет.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
