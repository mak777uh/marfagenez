def atom_block(a: dict) -> str:
    works = a.get("works") or []
    lines = [f"### {a['atom']}  [{a.get('domain')}/{a.get('kind')}]",
             f"**утверждение:** {a.get('statement')}"]
    if a.get("formula"):
        lines.append(f"**формула:** {a['formula']}")
    if a.get("notes"):
        lines.append(f"**заметки:** {a['notes']}")
    for w in works:
        lines.append(f"- DOI: {w.get('doi')} | локатор: {w.get('locator')} | доступ: {w.get('access')}")
        if w.get("quote"):
            lines.append(f"- цитата: {w['quote']}")
    return "\n".join(lines)


def node_block(n: dict) -> str:
    units = (n.get("math") or {}).get("units")
    latex = (n.get("math") or {}).get("latex") or ""
    lines = [f"### {n['id']}  [{n.get('kind')}]", f"**текст:** {n.get('text')}"]
    if latex:
        lines.append(f"**формула:** {latex}")
    if units:
        lines.append(f"**единицы:** {json.dumps(units, ensure_ascii=False)}")
    return "\n".join(lines)


def answer_request(req: dict, atoms: dict[str, dict], nodes: dict[str, dict],
                   edges: list[dict]) -> str:
    kind = req.get("kind")
    args = req.get("args") or {}
    head = f"# Срез по запросу: {kind}\n"
    if kind == "cells":
        ids = args.get("ids") or []
        parts = [atom_block(atoms[i]) for i in ids if i in atoms]
        missing = [i for i in ids if i not in atoms]
        body = "\n\n".join(parts) or "(ничего не найдено)"
        tail = f"\n\n_нет ячеек: {', '.join(missing)}_" if missing else ""
        return head + "\n" + body + tail
    if kind == "nodes":
        ids = args.get("ids") or []
        parts = [node_block(nodes[i]) for i in ids if i in nodes]
        missing = [i for i in ids if i not in nodes]
        body = "\n\n".join(parts) or "(ничего не найдено)"
        tail = f"\n\n_нет узлов: {', '.join(missing)}_" if missing else ""
        return head + "\n" + body + tail
    if kind == "orphans":
        deg = collections.Counter()
        for e in edges:
            deg[e["from"]] += 1
            deg[e["to"]] += 1
        group = args.get("group")
        ids = [i for i in atoms if deg[i] == 0 and (not group or i.startswith(group))]
        lines = [f"сирот: {len(ids)}" + (f" в группе {group}" if group else "")]
        lines += [f"- {i}" for i in sorted(ids)]
        return head + "\n" + "\n".join(lines)
    if kind == "standing":
        out = []
        for rel in (".coord/standing/S8-data-questions.md", "docs/PROBE-INSTRUCTION.md",
                    "docs/PROBE-PLAN.md", "docs/PROMPT-probe.md", "docs/PROBE-BRIDGE.md"):
            p = ROOT / rel
            if p.exists():
                out.append(f"## {rel}\n\n" + p.read_text(encoding="utf-8"))
        return head + "\n" + "\n\n".join(out)
    if kind == "audit":
        p = ROOT / "docs" / "STITCH-AUDIT.md"
        if not p.exists():
            return head + "\n(таблицы ещё нет)"
        text = p.read_text(encoding="utf-8")
        ids = args.get("ids") or []
        kept = [ln for ln in text.splitlines() if any(i in ln for i in ids)] if ids else text.splitlines()
        return head + "\n" + "\n".join(kept)
    return head + f"\nнеизвестный вид запроса: {kind}"


def norm_num(text: str) -> set[str]:
    """Числа из текста в нормализованном виде, включая научную запись с надстрочными цифрами."""
    import re as _re
    SUP = {"⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4", "⁵": "5", "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9",
           "⁻": "-", "⁺": "+"}
    out: set[str] = set()
    text = text or ""
    # сначала научная запись: 1,0·10⁻³ и 8×10⁻⁴
    for m in _re.finditer(r"(\d+(?:[.,]\d+)?)\s*[·×x]\s*10\s*(?:\^\s*([-+]?\d+)|([⁻⁺]?[⁰¹²³⁴⁵⁶⁷⁸⁹]+))", text):
        mant = float(m.group(1).replace(",", "."))
        if m.group(2) is not None:
            exp = int(m.group(2))
        else:
            exp = int("".join(SUP.get(c, "") for c in (m.group(3) or "")) or 0)
        val = mant * 10 ** exp
        out.add(f"{val:g}")
        out.add(f"{mant:g}e{exp}")
        out.add(m.group(0).replace(" ", ""))      # как записано в тексте: 1.67×10^-1
    # остальные числа
    for m in _re.finditer(r"\d+(?:[.,]\d+)?", text):
        raw = m.group(0).replace(",", ".")
        out.add(raw)
        try:
            out.add(f"{float(raw):g}")
        except ValueError:
            pass
    return out


def numbers_present(q: dict, atoms: dict[str, dict]) -> str | None:
    """Каждое число вопроса должно встречаться в тексте своих ячеек (иначе оно придумано)."""
    text = " ".join(
        " ".join(str((atoms[a].get(k) or "")) for k in ("statement", "formula", "notes"))
        + " " + " ".join(str(w.get("quote") or "") for w in (atoms[a].get("works") or []))
        for a in q.get("atoms") or [] if a in atoms)
    pool = norm_num(text)
    for n in q.get("numbers") or []:
        key = str(n).replace(",", ".").replace(" ", "")
        try:
            key = f"{float(key):g}"
        except ValueError:
            pass
        if key not in pool:
            return f"число {n!r} не встречается в тексте ячеек {q.get('atoms')}"
    return None


def q_hash(q: dict) -> str:
    """Legacy-отпечаток для совместимости с уже записанным probe-seen.json."""
    norm = re.sub(r"\s+", " ", str(q.get("question") or "").strip().lower())
    return hashlib.sha1(norm.encode("utf-8")).hexdigest()[:16]


def question_sha256(q: dict) -> str:
    """Canonical hash полного payload: kind/numbers/recalc и прочие поля значимы."""
    return canonical_sha256(q)


def validate_submission(path: pathlib.Path, atoms: dict[str, dict],
                        seen: set[tuple[str, tuple[str, ...], str]] | None = None) -> tuple[list[dict], list[str]]:
    good, bad = [], []
    seen = seen if seen is not None else set()
    if path.suffix != ".jsonl":
        return good, [f"{path.name}: не .jsonl"]
    raw = path.read_text(encoding="utf-8")
    # сначала пробуем весь файл как JSON: массив объектов или один объект
    items: list[tuple[int, str]] = []
    try:
        whole = json.loads(raw)
        if isinstance(whole, list):
            items = [(i, json.dumps(x, ensure_ascii=False)) for i, x in enumerate(whole, 1)]
        elif isinstance(whole, dict):
            items = [(1, json.dumps(whole, ensure_ascii=False))]
    except json.JSONDecodeError:
        pass
    if not items:
        # иначе — построчно, но собираем многострочные объекты по балансу скобок
        buf, depth, start = [], 0, 0
        for no, line in enumerate(raw.splitlines(), 1):
            if not line.strip() and not buf:
                continue
            buf.append(line)
            depth += line.count("{") - line.count("}")
            if depth <= 0:
                items.append((start or no, "\n".join(buf)))
                buf, depth, start = [], 0, 0
        if buf:
            items.append((start or 1, "\n".join(buf)))
    if len(items) > MAX_PER_FILE:
        bad.append(f"{path.name}: {len(items)} вопросов, потолок {MAX_PER_FILE}")
    for i, line in items:
        try:
            q = json.loads(line)
        except json.JSONDecodeError as exc:
            bad.append(f"{path.name}:{i}: не JSON ({exc.msg})")
            continue
        if not isinstance(q, dict):
            bad.append(f"{path.name}:{i}: нужен JSON object, получен {type(q).__name__}")
            continue
        problem = None
        if len(str(q.get("question") or "")) < 20:
            problem = "вопрос короче 20 символов"
        elif not isinstance(q.get("kind"), str) or q.get("kind") not in KINDS:
            problem = f"kind {q.get('kind')!r} не из {sorted(KINDS)}"
        elif not isinstance(q.get("atoms"), list) or not q["atoms"] \
                or not all(isinstance(atom, str) and atom in atoms for atom in q["atoms"]):
            problem = f"atoms не найдены в карте: {q.get('atoms')}"
        elif not isinstance(q.get("numbers"), list) or len(q["numbers"]) < 2:
            problem = "нужно ≥2 числа (numbers)"
        elif not q.get("verifiable"):
            problem = "нет поля verifiable: как проверить ответ"
        elif q.get("kind") in ("units", "order") and not q.get("recalc"):
            problem = "для units/order обязателен recalc — пересчёт"
        if not problem:
            problem = numbers_present(q, atoms)
        if not problem:
            signature = (str(q.get("kind")), tuple(sorted(q.get("atoms") or [])))
            sig = (*signature, question_sha256(q))
            legacy_sig = (*signature, "legacy:" + q_hash(q))
            if sig in seen or legacy_sig in seen:
                problem = "этот же вопрос уже принимался (совпал payload)"
            else:
                seen.add(sig)
        if problem:
            bad.append(f"{path.name}:{i}: {problem}")
        else:
            good.append(q)
    return good, bad


def _serve_locked(bridge: pathlib.Path) -> int:
    atoms, nodes = load_atoms(), load_nodes()
    edges = load_edges()
    req_dir, data_dir = bridge / "request", bridge / "data"
    out_dir, ack_dir, done_dir = bridge / "outbox", bridge / "ack", bridge / "done"
    for directory in (req_dir, data_dir, out_dir, ack_dir, done_dir):
        directory.mkdir(parents=True, exist_ok=True)

    journal_path = ROOT / "docs" / "PROBE-VERDICTS.jsonl"
    triage_path = ROOT / "docs" / "PROBE-TRIAGE.md"
    journal, known, warnings = load_journal(journal_path)
    for warning in warnings:
        print(f"предупреждение: {warning}", file=sys.stderr)

    # Старую Markdown-очередь и уже готовые verdict/ack импортируем до того,
    # как новые служебные ack смогут занять то же имя.
    early_events = legacy_triage_events(triage_path)
    for ack_path in sorted(ack_dir.glob("*.json")):
        try:
            value = json.loads(ack_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            print(f"предупреждение: ack {ack_path.name}: {exc}", file=sys.stderr)
            continue
        early_events.extend(verdict_event(record, ack_path.name) for record in ack_records(value))
    append_events(journal_path, early_events, known)
    journal, known, warnings = load_journal(journal_path)

    done = 0
    for req_path in sorted(req_dir.glob("*.json")) + sorted(req_dir.glob("*.req")):
        try:
            req = json.loads(req_path.read_text(encoding="utf-8"))
        except Exception as exc:
            atomic_write(ack_dir / f"{req_path.stem}.error", f"не разобрать запрос: {exc}\n")
            req_path.rename(req_dir / (req_path.name + ".bad"))
            continue
        if not isinstance(req, dict) or req.get("kind") not in REQUEST_KINDS:
            kind = req.get("kind") if isinstance(req, dict) else type(req).__name__
            atomic_write(ack_dir / f"{req_path.stem}.error",
                         f"вид запроса {kind!r} не разрешён: {sorted(REQUEST_KINDS)}\n")
            req_path.rename(req_dir / (req_path.name + ".bad"))
            continue
        atomic_write(data_dir / f"{req_path.stem}.md", answer_request(req, atoms, nodes, edges))
        move_to_done(req_path, done_dir)
        done += 1
        print(f"запрос {req_path.stem}: готово -> data/{req_path.stem}.md")

    state = bridge / "state" / "probe-seen.json"
    seen = load_seen(state, journal)
    received_at = dt.datetime.now().isoformat(timespec="seconds")
    inbox = ROOT / "literature" / "map" / "inbox"
    inbox.mkdir(parents=True, exist_ok=True)
    accepted_now = 0
    processed = 0
    # Только финальные .jsonl готовы. Внешний писатель обязан сделать
    # name.jsonl.tmp -> name.jsonl; .tmp намеренно не попадает в glob.
    for sub in sorted(out_dir.glob("*.jsonl")):
        source_payload = sub.read_bytes()
        source_sha256 = hashlib.sha256(source_payload).hexdigest()
        # Смерть после journal, но до ack/done: это та же незавершённая посылка,
        # а не новый дубль. Source hash не даёт затронуть события старой посылки
        # с тем же именем, а done проверяется по содержимому, не только по имени.
        recovering = not done_contains_source(done_dir, sub, source_payload) and any(
            event.get("source") == sub.name
            and event.get("source_sha256") == source_sha256
            and event.get("type") == "question"
            for event in journal
        )
        if recovering:
            for event in journal:
                if event.get("source") != sub.name or event.get("type") != "question" \
                        or event.get("source_sha256") != source_sha256:
                    continue
                q = event.get("payload") if isinstance(event.get("payload"), dict) else event
                atoms_q = q.get("atoms") or []
                if isinstance(atoms_q, list) and all(isinstance(atom, str) for atom in atoms_q):
                    signature = (str(q.get("kind")), tuple(sorted(atoms_q)))
                    seen.discard((*signature, question_sha256(q)))
                    if event.get("identity_version") != 2:
                        seen.discard((*signature, "legacy:" + q_hash(q)))
        good, bad = validate_submission(sub, atoms, seen)
        events = [question_event(q, sub.name, received_at, source_sha256) for q in good]
        ack = {"file": sub.name, "accepted": len(good), "rejected": len(bad), "reasons": bad,
               "source_sha256": source_sha256}
        if good:
            # Инвариант порядка: сначала durable inbox artifact, затем journal,
            # ack и done. После сбоя между любыми двумя шагами путь повторяется.
            out_file, payload, digest = inbox_artifact(inbox, sub.stem, good)
            ensure_inbox_artifact(out_file, payload)
            ack["written_to"] = str(out_file.relative_to(ROOT))
            ack["artifact_sha256"] = digest
            print(f"принято {len(good)} из {len(good) + len(bad)} -> {ack['written_to']}")
        else:
            print(f"{sub.name}: принято 0 из {len(bad)}")
        added = append_events(journal_path, events, known)
        accepted_now += added
        atomic_write(ack_dir / f"{sub.stem}.json",
                     json.dumps(ack, ensure_ascii=False, indent=2) + "\n")
        move_to_done(sub, done_dir)
        processed += 1

    write_seen(state, seen)
    journal, known, warnings = load_journal(journal_path)
    rebuild_triage(triage_path, journal)
    if accepted_now:
        print(f"триаж пересобран: docs/PROBE-TRIAGE.md (новых вопросов: {accepted_now})")

    if not done and not processed:
        print("очередь пуста: ни запросов, ни посылок")
    return 0


def serve(bridge: pathlib.Path) -> int:
    with bridge_lock(bridge):
        return _serve_locked(bridge)


def status(bridge: pathlib.Path) -> int:
    for name in ("queue", "request", "outbox", "data", "done", "ack"):
        d = bridge / name
        n = len([p for p in d.glob("*") if not p.name.endswith(".tmp")]) if d.exists() else 0
        print(f"{name:8} {n:3} файлов")
    rnd = bridge / "state" / "round"
    if rnd.exists():
        print("round:", rnd.read_text(encoding="utf-8").strip())
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="обмен файлами с агентом probe")
    ap.add_argument("--bridge", default=str(DEFAULT_BRIDGE))
    ap.add_argument("--serve", action="store_true", help="один проход: запросы и посылки")
    ap.add_argument("--status", action="store_true", help="состояние каталогов моста")
    ap.add_argument("--watch", type=int, default=0, metavar="СЕК",
                    help="крутить мост в цикле: проход, пауза СЕК, снова проход")
    args = ap.parse_args(argv)
    bridge = pathlib.Path(args.bridge)
    if not bridge.exists():
        print(f"нет каталога моста: {bridge}")
        return 1
    if args.status:
        return status(bridge)

    if not args.watch:
        try:
            return serve(bridge)
        except Exception as exc:                     # отказ виден кодом, без traceback
            print(f"проход упал: {exc}", file=sys.stderr)
            return 1

    # Цикл: агенты кладут файлы в любое время, мост подхватывает их сам.
    import time
    print(f"мост в режиме наблюдения: проход каждые {args.watch} с (Ctrl+C — стоп)")
    while True:
        try:
            serve(bridge)
        except KeyboardInterrupt:
            print("остановлено")
            return 0
        except Exception as exc:                     # проход не должен убивать цикл
            print(f"проход упал: {exc}")
        time.sleep(args.watch)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
