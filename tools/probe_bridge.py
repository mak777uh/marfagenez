def _fsync_dir(path: pathlib.Path) -> None:
    try:
        fd = os.open(path, os.O_RDONLY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    except OSError as exc:
        if exc.errno not in (errno.EINVAL, errno.ENOTSUP):
            raise


def atomic_write(path: pathlib.Path, text: str) -> None:
    """Запись готового файла через .tmp в том же каталоге + fsync + replace."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=f".{path.name}.tmp-", dir=path.parent)
    tmp = pathlib.Path(name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
        _fsync_dir(path.parent)
    finally:
        tmp.unlink(missing_ok=True)


def inbox_artifact(inbox: pathlib.Path, source: str, good: list[dict]) -> tuple[pathlib.Path, bytes, str]:
    """Детерминированный путь и хэш: повтор после сбоя не создаёт второй inbox-файл."""
    payload = ("\n".join(json.dumps(q, ensure_ascii=False) for q in good) + "\n").encode("utf-8")
    digest = hashlib.sha256(payload).hexdigest()
    return inbox / f"probe-{source}-{digest}.jsonl", payload, digest


def ensure_inbox_artifact(path: pathlib.Path, payload: bytes) -> None:
    if path.exists():
        if path.read_bytes() != payload:
            raise FileExistsError(f"inbox уже существует с другим содержимым: {path}")
        return
    atomic_write(path, payload.decode("utf-8"))


@contextlib.contextmanager
def bridge_lock(bridge: pathlib.Path):
    """Один проход на bridge: state, очереди и журнал не читаются параллельно."""
    state = bridge / "state"
    state.mkdir(parents=True, exist_ok=True)
    with (state / "probe-bridge.lock").open("a", encoding="utf-8") as fh:
        fcntl.flock(fh.fileno(), fcntl.LOCK_EX)
        yield


def canonical_sha256(value) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def event_key(event: dict) -> tuple[str, str]:
    # hash нового question event — canonical sha256 всего payload; source_sha256
    # остаётся отдельной идентичностью исходной посылки.
    return str(event.get("source", "")), str(event.get("hash", ""))


def load_journal(path: pathlib.Path) -> tuple[list[dict], set[tuple[str, str]], list[str]]:
    rows, keys, warnings = [], set(), []
    if not path.exists():
        return rows, keys, warnings
    for no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as exc:
            warnings.append(f"{path.name}:{no}: не JSON ({exc.msg})")
            continue
        if not isinstance(row, dict) or row.get("type") not in ("question", "verdict"):
            warnings.append(f"{path.name}:{no}: неизвестный тип события")
            continue
        rows.append(row)
        keys.add(event_key(row))
    return rows, keys, warnings


def append_events(path: pathlib.Path, events: list[dict], known: set[tuple[str, str]]) -> int:
    """Логически append-only: старые байты сохраняются, новые строки добавляются."""
    fresh = []
    for row in events:
        key = event_key(row)
        if key not in known:
            known.add(key)
            fresh.append(row)
    if not fresh:
        return 0
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    prefix = old + ("\n" if old and not old.endswith("\n") else "")
    payload = "".join(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n" for row in fresh)
    atomic_write(path, prefix + payload)
    return len(fresh)


def question_event(q: dict, source: str, stamp: str, source_sha256: str | None = None) -> dict:
    event = {
        "type": "question", "source": source, "hash": question_sha256(q),
        "identity_version": 2,
        "received_at": stamp, "kind": q.get("kind"), "question": q.get("question"),
        "atoms": q.get("atoms") or [], "numbers": q.get("numbers") or [], "payload": q,
    }
    if source_sha256 is not None:
        event["source_sha256"] = source_sha256
    return event


def verdict_event(record: dict, source: str) -> dict:
    return {
        "type": "verdict", "source": source, "hash": canonical_sha256(record),
        "verdict": record.get("verdict"), "score": record.get("score"), "record": record,
    }


def ack_records(value) -> list[dict]:
    """Новые ack — object/list; старые обёртки results/verdicts тоже читаем."""
    if isinstance(value, list):
        return [row for row in value if isinstance(row, dict)]
    if not isinstance(value, dict):
        return []
    if "verdict" in value or "score" in value:
        return [value]
    for name in ("verdicts", "results", "records"):
        if isinstance(value.get(name), list):
            return [row for row in value[name] if isinstance(row, dict)]
    nested = [row for row in value.values()
              if isinstance(row, dict) and ("verdict" in row or "score" in row)]
    return nested


def legacy_triage_events(path: pathlib.Path) -> list[dict]:
    """Одноразово переносим старую Markdown-очередь в журнал, не теряя историю."""
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    if GENERATED_MARKER in text:
        return []
    lines = text.splitlines()
    events = []
    for i, line in enumerate(lines):
        match = re.match(r"^- \*\*\[([^\]]+)\]\*\*\s+(.*)$", line)
        if not match:
            continue
        kind, question = match.groups()
        atoms, numbers = [], []
        if i + 1 < len(lines):
            meta = re.match(r"\s+- ячейки:\s*(.*?);\s*числа:\s*(.*)$", lines[i + 1])
            if meta:
                atoms = [x.strip() for x in meta.group(1).split(",") if x.strip()]
                numbers = [x.strip() for x in meta.group(2).split(",") if x.strip()]
        q = {"kind": kind, "question": question, "atoms": atoms, "numbers": numbers}
        events.append(question_event(q, "legacy:PROBE-TRIAGE.md", ""))
    return events


def load_seen(state: pathlib.Path, journal: list[dict]) -> set[tuple[str, tuple[str, ...], str]]:
    """State остаётся совместимым со старыми списками [kind, atoms, hash]."""
    seen: set[tuple[str, tuple[str, ...], str]] = set()
    if state.exists():
        try:
            raw = json.loads(state.read_text(encoding="utf-8"))
            if not isinstance(raw, list):
                raise ValueError("ожидался список")
            for item in raw:
                if not isinstance(item, (list, tuple)):
                    continue
                if len(item) == 3:
                    digest = str(item[2])
                    if len(digest) == 16 or digest == "old":
                        digest = "legacy:" + digest
                    seen.add((str(item[0]), tuple(item[1]), digest))
                elif len(item) == 2:
                    seen.add((str(item[0]), tuple(item[1]), "legacy:old"))
        except (OSError, UnicodeError, json.JSONDecodeError, ValueError, TypeError):
            # Журнал — второй источник истины: повреждённый state не разрешает
            # повторно принять уже записанный вопрос.
            pass
    for event in journal:
        if event.get("type") != "question":
            continue
        q = event.get("payload")
        if not isinstance(q, dict):
            q = event
        atoms = q.get("atoms") or []
        if isinstance(atoms, list) and all(isinstance(atom, str) for atom in atoms):
            signature = (str(q.get("kind")), tuple(sorted(atoms)))
            if event.get("identity_version") == 2:
                seen.add((*signature, question_sha256(q)))
            else:
                # Старый journal хранил только hash текста. Его точный payload
                # тоже узнаём, но другой kind/payload не должны потеряться.
                seen.add((*signature, "legacy:" + q_hash(q)))
                seen.add((*signature, question_sha256(q)))
    return seen


def write_seen(state: pathlib.Path, seen: set[tuple[str, tuple[str, ...], str]]) -> None:
    atomic_write(state, json.dumps(sorted([[kind, list(atoms), digest]
                                           for kind, atoms, digest in seen]),
                                  ensure_ascii=False, indent=2) + "\n")


def move_to_done(path: pathlib.Path, done: pathlib.Path) -> None:
    target = done / path.name
    if target.exists():
        target = done / f"{path.stem}-{time.time_ns()}{path.suffix}"
    os.rename(path, target)


def done_contains_source(done: pathlib.Path, source: pathlib.Path, payload: bytes) -> bool:
    """Отличает завершённую посылку от recovery даже при повторном имени файла."""
    for candidate in done.iterdir():
        if not candidate.is_file() or candidate.suffix != source.suffix:
            continue
        if candidate.name != source.name and not candidate.name.startswith(source.stem + "-"):
            continue
        if candidate.read_bytes() == payload:
            return True
    return False


def rebuild_triage(path: pathlib.Path, journal: list[dict]) -> None:
    """PROBE-TRIAGE.md — производная: вопросы и вердикты из append-only журнала."""
    unique = []
    seen = set()
    for event in journal:
        key = event_key(event)
        if key not in seen:
            seen.add(key)
            unique.append(event)
    questions = [row for row in unique if row.get("type") == "question"]
    verdicts = [row for row in unique if row.get("type") == "verdict"]
    if not unique and not path.exists():
        return
    by_kind = collections.Counter(str(row.get("kind") or (row.get("payload") or {}).get("kind"))
                                  for row in questions)
    lines = ["# Очередь вопросов `probe` на проверку", "", GENERATED_MARKER, "",
             f"Обновлено: {dt.datetime.now():%Y-%m-%d %H:%M}. "
             f"Вопросов в журнале: {len(questions)}. Вердиктов: {len(verdicts)}.", "",
             "| вид | сколько |", "|---|---|"]
    lines += [f"| {kind} | {count} |" for kind, count in sorted(by_kind.items())]
    lines += ["", "## Вопросы", ""]
    for event in questions:
        q = event.get("payload") if isinstance(event.get("payload"), dict) else event
        question = re.sub(r"\s+", " ", str(q.get("question") or "")).strip()
        atoms = ", ".join(map(str, q.get("atoms") or []))
        numbers = ", ".join(map(str, q.get("numbers") or []))
        lines.append(f"- **[{q.get('kind')}]** {question}")
        lines.append(f"  - ячейки: {atoms}; числа: {numbers}")
        lines.append(f"  - source: `{event.get('source')}`; sha256: `{event.get('hash')}`")
    if not questions:
        lines.append("(вопросов пока нет)")
    lines += ["", "## Вердикты", ""]
    for event in verdicts:
        score = json.dumps(event.get("score"), ensure_ascii=False)
        lines.append(f"- `{event.get('source')}`: verdict={event.get('verdict')}, score={score}")
        lines.append(f"  - sha256: `{event.get('hash')}`")
    if not verdicts:
        lines.append("(вердиктов пока нет)")
    atomic_write(path, "\n".join(lines) + "\n")


