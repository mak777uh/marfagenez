"""Подстановка измеренных чисел в двухосевую формулу.

Данные (B18-01-0003): конечный уровень один и тот же (1640 против 640 мосмоль/кг, то есть превышение
1000 мосмоль/кг), исход разный: мгновенный скачок — 30% выживших, линейный проход за 20 часов — 89%.

Формула: (L/L*) + (v/v*)^2 <= 1.

Скрипт считает: какие значения v* совместимы с этими двумя наблюдениями при разных долях
L/L*, и какие промежуточные скорости дали бы промежуточный исход. Ничего не моделирует сверх
арифметики формулы.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CHECK-OSMOTIC.md"

LEVEL = 1000.0     # мосмоль/кг, превышение над 640
RAMP_H = 20.0      # ч
V_RAMP = LEVEL / RAMP_H  # 50 мосмоль/кг/ч


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Проверка формулы на измеренных числах: осмолярность")
    a("")
    a("Сгенерировано `tools/check_osmotic.py`. Только арифметика формулы `(L/L*) + (v/v*)^2 <= 1`.")
    a("")
    a("## Данные")
    a("")
    a(f"- превышение уровня: **{LEVEL:.0f} мосмоль/кг** (1640 против 640), одинаковое в обоих опытах;")
    a(f"- медленный подход: **{V_RAMP:.0f} мосмоль/кг/ч** (за {RAMP_H:.0f} ч) — выжило **89%**;")
    a("- мгновенный скачок: скорость неограниченна — выжило **30%**.")
    a("")
    a("## Что следует из формулы")
    a("")
    a("Для медленного подхода, раз он дал выживание:")
    a("")
    a("    (L/L*) + (v/v*)^2 <= 1   =>   v* >= v / sqrt(1 - L/L*)")
    a("")
    a("| доля уровня L/L* | какой должна быть v*, мосмоль/кг/ч |")
    a("|---|---|")
    table = []
    for frac in (0.5, 0.7, 0.9, 0.95, 0.99):
        vstar = V_RAMP / (1.0 - frac) ** 0.5
        table.append((frac, vstar))
        a(f"| {frac:.2f} | не меньше {vstar:.0f} |")
    a("")
    a("## Что это предсказывает и как проверить")
    a("")
    a("Если формула верна, то при промежуточных скоростях исход должен лежать между 30% и 89%:")
    a("")
    a("| скорость, мосмоль/кг/ч | предсказание при L/L* = 0,5 (v* ≈ 71) | при L/L* = 0,9 (v* ≈ 158) |")
    a("|---|---|---|")
    for v in (50, 70, 100, 160, 250, 400):
        row = []
        for _, vstar in ((0.5, table[0][1]), (0.9, table[2][1])):
            term = (v / vstar) ** 2
            if term > 1:
                row.append("срыв")
            else:
                row.append(f"выживает (запас {1 - term:.2f})")
        a(f"| {v} | {row[0]} | {row[1]} |")
    a("")
    a("## Что это даёт")
    a("")
    a("1. Числа **совместимы** с формулой при `v*` от 71 до бесконечности: двух точек недостаточно, чтобы")
    a("   получить `v*` однозначно.")
    a("2. Но они **исключают** одну вещь: если бы порог по скорости отсутствовал (то есть `v*` бесконечно),")
    a("   исход при мгновенном скачке был бы таким же, как при медленном подходе. Он не такой.")
    a("3. Значит вторая ось нужна, а не только первая. Это первое **эмпирическое** основание для члена")
    a("   `(v/v*)^2`, а не только аналогия с инженерным законом безопасности.")
    a("")
    a("## Решающий опыт")
    a("")
    a("Нужны **промежуточные скорости**: 70, 100, 160, 250 мосмоль/кг/ч. Если выживание падает между 50 и")
    a("160 — `v*` попадает в этот интервал, и формула проверена. Если остаётся 89% до 400 и выше —")
    a("второй член надо переписать (например, в первой степени).")
    a("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
