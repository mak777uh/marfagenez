"""Пересчёт цен границы к одной форме: P/A = J * dmu — и проверка, что из этого следует.

Все числа берутся из карты (atoms.jsonl) или из явно указанных констант; результат пишется в
docs/DEEPEN-01-BOUNDARY.md. Скрипт не «знает» ответа: он печатает величины, а вывод формулируется
по ним.

Usage: python3 tools/deepen_boundary.py [--write]
"""

from __future__ import annotations

import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "DEEPEN-01-BOUNDARY.md"

NA = 6.02214076e23
DG_ATP = 50e3          # Дж/моль, из B7-03-0003 (консервативно)
GLUCOSE_J_PER_MG = 15.6  # Дж/мг (3.74 ккал/г)
S_PER_DAY = 86400.0

# --- исходные величины из карты
pump_lo, pump_hi = 8e-4, 8e-3          # Вт/м2, B7-03-0001
neuron = 0.3                            # Вт/м2, B7-03-0003
lipid_one_off = 0.12                    # Дж/м2, B7-03-0002
protein_turnover = 2e-5                 # Вт/м2, B7-03-0002
ro_power = 1.33                         # Вт/м2, B11-08-0002
plant_lo, plant_hi = 6.0, 10.0         # мг глюкозы/(г сух. массы * сутки), B10-05-0001
lipid_th = (2.0 * 3600, 2.5 * 3600)    # с, B8-03-0001-b


def atp_flux(power: float) -> float:
    """молекул ATP/(мкм2*с) при данном Вт/м2 и dG_ATP."""
    mol_per_m2_s = power / DG_ATP
    return mol_per_m2_s * NA / 1e12


def lipid_power(t_half: float) -> float:
    """Мощность замещения липидов, если разовая цена 0.12 Дж/м2 за время t_half."""
    return lipid_one_off * math.log(2) / t_half


def plant_power_per_kg(lo: float, hi: float) -> tuple[float, float]:
    """мг глюкозы/(г*сутки) -> Вт/кг сухой массы."""
    return (lo * GLUCOSE_J_PER_MG / S_PER_DAY * 1000,
            hi * GLUCOSE_J_PER_MG / S_PER_DAY * 1000)


def ro_flux() -> float:
    q_feed = (74.4 + 105) / 3600      # м3/с
    area = 140 * 41                    # м2
    return q_feed / area


def main(argv: list[str]) -> int:
    lines: list[str] = []
    add = lines.append

    add("# Углубление 01 — цена границы в одной форме")
    add("")
    add("Сгенерировано `tools/deepen_boundary.py` из величин карты; все пересчёты ниже — арифметика,")
    add("константы указаны явно (dG_ATP = 50 кДж/моль, глюкоза = 15,6 Дж/мг).")
    add("")

    add("## 1. Одна форма для всех")
    add("")
    add("Мощность на площадь равна потоку через границу, умноженному на движущую силу:")
    add("")
    add("    P/A = J * dmu")
    add("")
    add("Для насосов: `P/A = J_ATP * dG_ATP`. Для гидравлического интерфейса: `P/A = J_water * dP`.")
    add("")
    add("Если это верно, то цена на площадь — **не свойство материала**, а мера потока, который граница")
    add("обслуживает. Проверяем на числах.")
    add("")

    add("## 2. Что получается из карты")
    add("")
    add("### 2.1 Мембрана: насосы против потока ATP")
    add("")
    add(f"- мощность {pump_lo:.0e}–{pump_hi:.0e} Вт/м² (B7-03-0001)")
    add(f"- поток ATP = {atp_flux(pump_lo):.0f}–{atp_flux(pump_hi):.0f} молекул/(мкм²·с)")
    add(f"- нейрон при 500 Гц: {neuron} Вт/м² → {atp_flux(neuron):.0f} молекул/(мкм²·с)")
    add("")
    add("### 2.2 Мембрана: построение против поддержания")
    add("")
    for th in lipid_th:
        add(f"- при полужизни липидов {th/3600:.1f} ч разовая цена {lipid_one_off} Дж/м² даёт "
            f"{lipid_power(th):.1e} Вт/м²")
    add(f"- оборот белков: {protein_turnover:.0e} Вт/м²")
    add("")
    add("Вывод: построение липидов даёт мощность на 2–3 порядка ниже насосов. Поддержание дороже.")
    add("")

    add("### 2.3 Растение: ионное поддержание в ресурсном бюджете")
    add("")
    plo, phi = plant_power_per_kg(plant_lo, plant_hi)
    add(f"- {plant_lo:.0f}–{plant_hi:.0f} мг глюкозы/(г сух. массы·сут) = {plo:.2f}–{phi:.2f} Вт/кг сухой массы")
    add("- перевод в Вт/м² требует площади мембран на грамм сухой массы; в карте этого числа нет —")
    add("  это честная неясность, а не арифметика.")
    add("")

    add("### 2.4 Инженерный интерфейс: обратный осмос")
    add("")
    add(f"- поток через мембрану {ro_flux():.2e} м³/(м²·с)")
    add(f"- мощность {ro_power} Вт/м² при dP = 153 кПа")
    add("")
    add("Проверка формы: `J * dP` = "
        f"{ro_flux() * 153e3:.2f} Вт/м² — совпадает с пересчётом из B11-08-0002, значит форма верна.")
    add("")

    add("## 3. Что из этого следует (и что нет)")
    add("")
    m_water = ro_flux() * 3.343e28 / 1e12      # молекул/(мкм2*с)
    add("1. **Сравнивать Вт/м² между клеткой и установкой бессмысленно без потока.** У клетки")
    add(f"   {atp_flux(pump_lo):.0f}–{atp_flux(pump_hi):.0f} молекул ATP/(мкм²·с); у RO через ту же")
    add(f"   площадь проходит {m_water:.1e} молекул воды/(мкм²·с), то есть на 7–8 порядков больше.")
    add("2. **На единицу перенесённого вещества клетка платит на 4 порядка больше**, чем установка:")
    add(f"   {DG_ATP/NA:.1e} Дж на молекулу ATP против {153e3*18e-6/NA:.1e} Дж на молекулу воды")
    add("   (18 см³/моль — молярный объём воды). Обмена «дорого/дешево» тут нет: клетка платит")
    add("   больше за молекулу и переносит на 7–8 порядков меньше молекул — это разные режимы, а не")
    add("   разные материалы.")
    add("3. **Значит «цена границы» измерима, но не универсальна.** Правильная безразмерная величина —")
    add("   не Вт/м², а **энергия на единицу перенесённого вещества** или доля бюджета за время.")
    add("   Это подтверждает `I-014` (сравнение по долям) и ограничивает её.")
    add("4. **Отсюда следует риск нашей модели:** если в критерии использовать Вт/м², он будет")
    add("   чувствителен к геометрии и потоку, а не к жизни. Надо нормировать на поток или на бюджет.")
    add("")

    add("## 4. Неясности, которые надо закрыть поиском")
    add("")
    add("| что неясно | почему важно | как закрыть |")
    add("|---|---|---|")
    add("| площадь мембран на грамм сухой массы растения | без неё Вт/кг не переводится в Вт/м² | искать 'membrane area per gram dry weight leaf' |")
    add("| P/O и ATP на глюкозу (30–32 против 38) | меняет пересчёт глюкозы в ATP на 20% | взять современную оценку с цитатой |")
    add("| доля ATP на ремонт (пустота B10-01) | главный недостающий член критерия | эксперимент с ингибитором репарации + дыхание |")
    add("| толщина раковины и матрицы | цена на площадь у раковины несравнима с мембраной без толщины | искать толщину и долю матрицы у Nucella |")
    add("")
    text = "\n".join(lines) + "\n"
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
