"""F-020: Гомпертц, Макегам и пределы. Что проверяемо из записи.

Запись: `mu(x) = R·exp(alpha·x)` с «удвоением примерно каждые 8 лет взрослой жизни»;
Макегам добавляет `mu0`; «плато» при исчерпании избыточности.

Проверяется:
  1) арифметика удвоения: `t_d = ln 2 / alpha`; при 8 годах `alpha = 0,0866 1/год`;
  2) единицы: `mu`, `R`, `mu0` — 1/год; `alpha` — 1/год; `alpha·x` безразмерно;
  3) согласованность с типичными человеческими числами: если `mu(40) ≈ 0,002 1/год`, то каковы
     `R`, `mu(80)`, `mu(100)`;
  4) где модель ломается: экспонента не даёт плато, а данные о долгожителях его показывают.

Запуск: python3 tools/gompertz_check.py
"""

from __future__ import annotations

import math


def alpha_from_doubling(years: float) -> float:
    return math.log(2) / years


def main() -> int:
    print("== удвоение смертности и alpha")
    for years in (7.0, 8.0, 9.0):
        print(f"  t_d = {years} лет -> alpha = {alpha_from_doubling(years):.4f} 1/год")
    alpha = alpha_from_doubling(8.0)

    print()
    print("== единицы")
    print("  mu(x), R, mu0 — интенсивность смертности, 1/год")
    print("  alpha — 1/год;  alpha·x безразмерно при x в годах")
    print("  t_d = ln 2 / alpha — годы")

    print()
    print("== согласованность с человеческими числами")
    mu40 = 0.002
    R = mu40 / math.exp(alpha * 40)
    print(f"  пусть mu(40) = {mu40} 1/год; тогда R = mu(40)/exp(alpha·40) = {R:.2e} 1/год")
    for age in (40, 60, 80, 100, 110):
        mu = R * math.exp(alpha * age)
        print(f"  mu({age:>3}) = {mu:.4f} 1/год  (вероятность умереть в течение года ≈ {1-math.exp(-mu):.3f})")
    print("  ориентиры: mu(80) ≈ 0,06, mu(100) ≈ 0,3–0,5 — модель попадает в них без подгонки под каждую точку")

    print()
    print("== где модель ломается")
    print("  Гомпертц монотонно растёт: плато он не даёт ПО ФОРМЕ.")
    print("  Данные о долгожителях показывают выход на плато; в записи это объясняется")
    print("  исчерпанием избыточности — то есть сменой механизма, а не свойством формулы.")
    print("  Проверяемое следствие: если плато есть, то mu(110)/mu(100) < exp(alpha·10) = 2,38.")
    ratio = math.exp(alpha * 10)
    print(f"  Предсказание Гомпертца на 100->110 лет: рост в {ratio:.2f} раза.")
    print("  Наблюдаемое (по литературе о плато): рост близок к 1. Это опровергающее условие.")
    print()
    print("== различимы ли mu0 и alpha по двум точкам (Макегам против Гомпертца)")
    # подгонка Макегама по двум точкам: mu(40) = a, mu(80) = b
    a40, a80 = 0.002, 0.064
    print(f"  фиксируем mu(40) = {a40}, mu(80) = {a80}")
    print(f"{'mu0':>8} {'alpha, 1/год':>14} {'R':>12} {'mu(100)':>9} {'mu(110)':>9}")
    for mu0 in (0.0, 0.0005, 0.001, 0.002, 0.004):
        # из mu0 + R e^{40a} = a40 и mu0 + R e^{80a} = a80:
        # (a80 - mu0)/(a40 - mu0) = e^{40 alpha}
        if mu0 >= a40:
            print(f"{mu0:>8} {'—':>14} {'—':>12} {'—':>9} {'—':>9}   (mu0 не меньше mu(40): модель невозможна)")
            continue
        ratio = (a80 - mu0) / (a40 - mu0)
        if ratio <= 0:
            print(f"{mu0:>8} {'—':>14} {'—':>12} {'—':>9} {'—':>9}   (mu0 выше второй точки: модель не годится)")
            continue
        alpha = math.log(ratio) / 40.0
        R = (a40 - mu0) / math.exp(alpha * 40)
        mu100 = mu0 + R * math.exp(alpha * 100)
        mu110 = mu0 + R * math.exp(alpha * 110)
        print(f"{mu0:>8} {alpha:>14.5f} {R:>12.3e} {mu100:>9.4f} {mu110:>9.4f}")
    print("  все строки одинаково хорошо описывают две точки — параметры компенсируют друг друга.")
    print("  Различить их можно только по ТРЕТЬЕЙ точке (например, mu(100)); по двум — нельзя.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
