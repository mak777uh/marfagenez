"""Сводка порогов по темпам из разных областей и попытка безразмерной оси.

Все числа — из принятых ячеек карты. Скрипт не моделирует, а проверяет РАЗМЕРНОСТЬ:
можно ли вообще поставить эти пороги на одну ось.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "COLLAPSE.md"

# (область, величина порога, единица, размерность скорости, что переключается, ячейка)
THRESHOLDS = [
    ("коррозия, растрескивание", 1e-5, "1/с", "1/время", "линейный → нелинейный рост", "DIP51-0001"),
    ("течение металла", 1e4, "1/с", "1/время", "дислокации → торможение", "DIP51-0006"),
    ("усталость, частота", 0.1, "1/с", "1/время", "оптимум водородного ускорения", "DIP51-0004"),
    ("катализ (число Thiele)", 0.4, "безразмерное", "нет", "кинетика → смешанный режим", "DIP51-0008"),
    ("катализ (число Thiele)", 4.0, "безразмерное", "нет", "смешанный → диффузия", "DIP51-0008"),
    ("осмос, подъём", 3.0, "мОсм/мин", "концентрация/время", "защита не включается", "DIP47-0002"),
    ("осмос, спуск", 27.0, "мОсм/мин", "концентрация/время", "срыв объёма", "DIP47-0002"),
    ("дрожжи, порог Hog1", 12.1, "мМ/мин", "концентрация/время", "включается сигнализация", "B18-01-0003"),
    ("радиация, мощность дозы", 0.01, "Гр/мин", "энергия/(масса·время)", "репарация успевает", "B20-01-0002"),
    ("криобиология, охлаждение", 187.0, "°C/мин", "температура/время", "максимум выживания", "B24-01-0003"),
    ("криобиология, отогрев", 1.4e5, "°C/мин", "температура/время", "обрыв по льду", "DIP50-0004"),
    ("осмос, порог включения", 5.0, "МПа", "давление", "включается инактивация", "B22-01-0001"),
]

DIMENSIONS = {
    "1/время": "1/с",
    "концентрация/время": "мМ/(л·мин)",
    "энергия/(масса·время)": "Гр/мин",
    "температура/время": "°C/мин",
    "давление": "МПа",
    "нет": "безразмерное",
}


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Можно ли свести пороги к одной оси")
    a("")
    a("Сгенерировано `tools/collapse.py` по числам принятых ячеек. Проверяется только одно: "
      "**размерность** порогов, а не их совпадение.")
    a("")
    a("## Пороги, которые у нас есть")
    a("")
    a("| область | порог | единица | размерность | что переключается | ячейка |")
    a("|---|---|---|---|---|---|")
    for name, val, unit, dim, what, cell in THRESHOLDS:
        val_s = f"{val:.0e}" if val < 1e-3 or val > 1e4 else f"{val:g}"
        a(f"| {name} | {val_s} | {unit} | {dim} | {what} | `{cell}` |")
    a("")
    dims = {}
    for *_, dim, _what, _cell in THRESHOLDS:
        dims.setdefault(dim, 0)
        dims[dim] += 1
    a("## Сколько разных размерностей")
    a("")
    for dim, n in sorted(dims.items(), key=lambda kv: -kv[1]):
        a(f"- **{dim}** ({DIMENSIONS.get(dim, dim)}): {n}")
    a("")
    a("## Вывод по размерности")
    a("")
    a(f"Размерностей: **{len(dims)}**. Это значит, что единой оси `v/v*` в исходных единицах **нет и быть "
      "не может**.")
    a("")
    a("Чтобы сравнивать, каждую скорость нужно поделить на характерную скорость **своей** системы:")
    a("тогда получится безразмерное число. Но характерная скорость опубликована не для всех систем:")
    a("")
    a("- **есть**: число Thiele (0,4 и 4) в катализе, фактор Леа–Кэтчесайда в радиобиологии,")
    a("  критические скорости стеклования CCR/CWR в криобиологии, порог Hog1 у дрожжей;")
    a("- **нет**: для коррозионного растрескивания и для течения металла порог опубликован в 1/с,")
    a("  но характерная скорость системы (к чему нормировать) в наших ячейках отсутствует.")
    a("")
    a("## Что уже свёрнуто в литературе")
    a("")
    a("Внутри отдельных полей свёртка **существует** и работает:")
    a("")
    a("- катализ: одно число Thiele задаёт режим, и он же сравнивает системы между собой;")
    a("- радиобиология: фактор G сводит время облучения и константу репарации;")
    a("- криобиология: отношение скорости к критической (CCR/CWR) сравнивает растворы.")
    a("")
    a("**Межсистемной свёртки нет.** Исполнитель по `B19-05` проверил открытые тексты и не нашёл работы,")
    a("где разные биологические системы сведены к одной оси `v/v*` с совпадающими кривыми.")
    a("")
    a("## Что это значит")
    a("")
    a("1. Похожесть структуры (порог + смена механизма) **не означает** общую числовую ось: единицы разные,")
    a("   и нормировать пока нечем.")
    a("2. Сравнивать системы можно **только по безразмерному отношению**, а его надо либо взять из")
    a("   литературы (Thiele, G, CCR), либо измерить самому — чего мы не делаем.")
    a("3. Поэтому честная формула — **не одна кривая**, а **таблица режимов с порогами в единицах системы**")
    a("   (см. `docs/FORMULA-SWITCH.md`).")
    a("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
