"""Проверка v3 сразу на двух наборах: `R(D) = C0·exp(−D/a)·(1 + D/b)`.

Данные (из карты):
  DIP59-0001 (RIF-фокусы):  разрешение при 2 Гр примерно в 5 раз медленнее, чем при 0,1 Гр
                            => R(0,1)/R(2) = 5
  DIP59-0006 (53BP1-фокусы): t½ = 3,1 ч при 5–10 мГр против 2,7 ч при 500 мГр
                            => R(0,0075)/R(0,5) = 2,7/3,1 = 0,871 (быстрее при большей дозе)

Форма v3 предсказывает: R растёт до `D* = a − b` (при `a > b`), потом падает.

Вопрос: существует ли пара (a, b) с a > b, при которой ОБА отношения воспроизводятся одновременно,
и попадает ли при этом `D*` в разумное окно (0,5…2 Гр)?

Если решения нет — v3 опровергнута теми же данными, для которых создавалась.
Если есть — v3 проходит нетривиальную проверку согласованности.

Запуск: python3 tools/v3_two_datasets.py
"""

from __future__ import annotations

import math

D1_LOW, D1_HIGH, RATIO1 = 0.1, 2.0, 5.0          # RIF
D2_LOW, D2_HIGH, RATIO2 = 0.0075, 0.5, 2.7 / 3.1  # 53BP1


def R(d: float, a: float, b: float) -> float:
    return math.exp(-d / a) * (1.0 + d / b)


def ratios(a: float, b: float) -> tuple[float, float]:
    r1 = R(D1_LOW, a, b) / R(D1_HIGH, a, b)
    r2 = R(D2_LOW, a, b) / R(D2_HIGH, a, b)
    return r1, r2


def main() -> int:
    print("цель: R(0,1)/R(2) = 5,000  и  R(0,0075)/R(0,5) = 0,871")
    print()
    best = None
    for a in [0.05 * i for i in range(1, 400)]:          # a: 0,05 … 19,95
        for b in [0.05 * j for j in range(1, 400)]:
            if a <= b:
                continue
            r1, r2 = ratios(a, b)
            err = abs(math.log(r1 / RATIO1)) + abs(math.log(r2 / RATIO2))
            if best is None or err < best[0]:
                best = (err, a, b, r1, r2)
    err, a, b, r1, r2 = best
    print(f"лучшая пара: a = {a:.2f}, b = {b:.2f}")
    print(f"  воспроизводит: R(0,1)/R(2) = {r1:.3f} (цель 5,000);  R(0,0075)/R(0,5) = {r2:.3f} (цель 0,871)")
    print(f"  ошибка (сумма |ln|): {err:.3f}")
    print(f"  D* = a − b = {a - b:.2f} Гр")
    print()

    if err > 0.15:
        print("ВЫВОД: v3 НЕ воспроизводит оба отношения одновременно — форма опровергнута теми же данными.")
        return 1

    dstar = a - b
    print("ВЫВОД: v3 воспроизводит оба отношения одной парой параметров.")
    print(f"        Максимум предсказан при D* = {dstar:.2f} Гр, то есть между двумя наборами.")
    print("        Это НЕ подтверждение механизма, но согласованность, которой не было у v2:")
    print("        v2 (монотонное падение) не может дать роста 0,0075 -> 0,5 Гр вовсе.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
