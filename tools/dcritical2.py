"""Точка невозврата, версия 2: ремонт ограничен доступным грузом.

Что исправлено против версии 1 (`docs/FORMULA-DCRITICAL.md` до круга 120):
  * при D=0 модель v1 давала dD/dt = P0 - C0 < 0, то есть «удаление того, чего нет»;
  * равновесие v1 неустойчиво и является сепаратрисой, а не стабильным плато.

Версия 2: R(D) = min(C(D), k*D), то есть ремонт не может превысить ни мощность аппарата, ни
количество доступного повреждения. Это **моя конструкция**; числа ниже — иллюстрация структуры.

Запуск: python3 tools/dcritical2.py [--write]
"""

from __future__ import annotations

import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "FORMULA-DCRITICAL.md"


def c_of_d(d: float, c0: float, d_cap: float) -> float:
    return c0 * math.exp(-d / d_cap)


def repair(d: float, c0: float, d_cap: float, k: float) -> float:
    return min(c_of_d(d, c0, d_cap), k * d)


def net(d: float, p0: float, c0: float, d_cap: float, k: float) -> float:
    return p0 - repair(d, c0, d_cap, k)


def equilibria(p0, c0, d_cap, k, hi=50.0, n=200000):
    """Грубый поиск всех корней net(D)=0 на [0, hi] сменой знака."""
    roots = []
    prev = net(1e-9, p0, c0, d_cap, k)
    for i in range(1, n + 1):
        d = hi * i / n
        cur = net(d, p0, c0, d_cap, k)
        if prev == 0:
            roots.append(hi * (i - 1) / n)
        elif prev * cur < 0:
            lo, hi2 = hi * (i - 1) / n, d
            for _ in range(80):
                mid = (lo + hi2) / 2
                if net(lo, p0, c0, d_cap, k) * net(mid, p0, c0, d_cap, k) <= 0:
                    hi2 = mid
                else:
                    lo = mid
            roots.append((lo + hi2) / 2)
        prev = cur
    return roots


def stability(d: float, p0, c0, d_cap, k) -> str:
    h = 1e-6
    deriv = (net(d + h, p0, c0, d_cap, k) - net(d - h, p0, c0, d_cap, k)) / (2 * h)
    if abs(deriv) < 1e-9:
        return "нейтрально"
    return "устойчиво" if deriv < 0 else "неустойчиво"


