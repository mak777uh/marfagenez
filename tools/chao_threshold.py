"""Критерий Chao `Πλ ≤ 1/6`: только размерность и пределы.

Важно: константа `1/6` здесь **не выводится** — она из модели Chao (симметричное деление, `a = 1`).
Проверяется то, что проверяемо без неё:
  1) `Πλ` безразмерно (время повреждения × темп повреждения);
  2) пределы: `λ → 0` — равновесие есть всегда; `Π → ∞` при том же `λ` — равновесия нет;
  3) граница — линия `λ = (1/6)/Π`, а не число: для каждого `Π` свой критический темп.

Запуск: python3 tools/chao_threshold.py
"""

from __future__ import annotations


def main() -> int:
    print("== размерность")
    print("  Π — время повреждения, с")
    print("  λ — темп повреждения, 1/с")
    print("  Π·λ — безразмерно; порог 1/6 тоже безразмерен — размерность согласована")

    print()
    print("== пределы")
    print("  λ → 0  ⇒ Πλ → 0 < 1/6  ⇒ равновесие существует при любой Π")
    print("  Π → ∞  ⇒ Πλ → ∞ > 1/6  ⇒ равновесия нет: повреждение копится быстрее, чем делится")
    print("  Πλ = 1/6 — граница; при равенстве критерий нестрогий (равновесие на краю)")

    print()
    print("== граница — линия, а не число: λ_crit = (1/6)/Π")
    for Pi in (0.6, 1.0, 2.0, 6.0):
        print(f"  Π = {Pi:>4}: λ_crit = {(1/6)/Pi:.3f} 1/с")

    print()
    print("== проверка записанного примера из карты")
    Pi_lambda = 0.10
    print(f"  Πλ = {Pi_lambda}: {Pi_lambda} ≤ 1/6 = {1/6:.3f} → {'равновесие есть' if Pi_lambda <= 1/6 else 'нет'}")

    print()
    print("== что НЕ проверено")
    print("  зависимость порога от асимметрии деления a: в записи сказано, что a сдвигает порог,")
    print("  но формула сдвига не выписана и здесь не выводится — это отдельный вопрос.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
