"""Таблица «безразмерное число → режим» по итогам сшивки двух карт.

Собирает только те безразмерные величины, которые уже есть в принятых ячейках, и показывает,
какой режим они переключают. Ничего не моделирует: если у числа нет измеренного порога — так и пишет.

Запуск: python3 tools/dimensionless_regimes.py [--write]
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "DIMENSIONLESS-REGIMES.md"

# (величина, определение, значение/порог, режим до, режим после, источник, проверено)
ROWS = [
    ("Дамкёлер Da", "скорость реакции / скорость переноса", "порог ≈ 1",
     "перенос быстрее реакции", "реакция быстрее переноса", "DIP53-0002", "да"),
    ("Пекле Pe", "адвекция / диффузия", "3,3·10⁻² и ≈10³",
     "перенос диффузией", "перенос адвекцией", "DIP53-0005, DIP53-0003", "да"),
    ("Дин De", "время релаксации / время течения", "не измерен",
     "течение успевает за релаксацией", "релаксация отстаёт", "DIP53-0006", "нет порога"),
    ("Био Bi", "внутреннее сопротивление / внешнее", "0,238 и 0,047; порог Bi < 1/6",
     "поле внутри однородно", "внутри есть градиент", "DIP53-0011, DIP54-0008", "да, два значения"),
    ("Тиле φ", "реакция / диффузия в поре", "не измерен как порог",
     "концентрация однородна", "концентрация падает к центру", "DIP53-0009", "нет порога"),
    ("κ (доля ассимиляции в сому)", "поток в сому / весь поток", "медиана 0,9",
     "почти всё в рост", "существенная доля на поддержание", "DIP56-0011, DIP28-0009", "да"),
    ("Π·λ (Chao)", "вероятность успеха деления × число каналов", "≤ 1/6",
     "равновесие возможно", "равновесие невозможно", "C-004", "да (теорема)"),
    ("H(T) (кумулятивная опасность)", "интеграл темпа по времени", "порог 5 МПа — давление, НЕ H(T)",
     "накопление без отказа", "порог отказа", "B22-01-0001, F-001", "аналог: перевод МПа в H(T) не доказан"),
    ("τ = k·t (безразмерное время)", "темп × время", "не измерен",
     "процесс не завершён", "процесс завершён", "DIP46-0001", "нет порога"),
    ("δ ∝ √(2 ln N)", "сдвиг порога от числа вариантов", "проверено и провалено",
     "порог не зависит от N", "порог растёт с N", "F-014 / FINDING-339", "провалено"),
    ("Na/K-доля", "работа насосов / бюджет ATP", ">55 % в мозге",
     "граница дешева", "граница дорога", "DIP56-0007, DIP56-0009", "да (одна система)"),
]


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Безразмерные числа и режимы, которые они переключают")
    a("")
    a("Сгенерировано `tools/dimensionless_regimes.py`. Взяты **только** величины, уже принятые в ячейках;")
    a("числа — из этих ячеек, не из новых расчётов.")
    a("")
    a("| величина | определение | значение / порог | режим до | режим после | источник | статус |")
    a("|---|---|---|---|---|---|---|")
    for name, defn, val, before, after, src, ok in ROWS:
        a(f"| **{name}** | {defn} | {val} | {before} | {after} | {src} | {ok} |")
    a("")
    a("## Что видно")
    a("")
    a("1. **Измеренный порог есть у пяти величин из одиннадцати:** Дамкёлер, Пекле, Био, κ и Π·λ.")
    a("   У остальных либо нет порога (Дин, Тиле, τ), либо порог проверен и **провален** (√(2 ln N)).")
    a("2. **Пороги лежат около единицы или ниже:** Da ≈ 1, Bi = 0,238 и 0,047 (порог Bi < 1/6), κ = 0,9,")
    a("   Π·λ ≤ 1/6. Строка `H(T)` — **аналог, не тождество**: 5 МПа измерены как давление, а `H(T)` —")
    a("   интеграл темпа; перевода одного в другое нет.")
    a("   Это не случайность: у безразмерного числа «порядка единицы» режим меняется, у «порядка 10³»")
    a("   (Пекле) — уже давно сменился, и там порог не информативен.")
    a("3. **Ось сшивки — именно эти числа.** Пары между картами шли по долям и порогам, а не по")
    a("   абсолютным скоростям (`docs/STITCH-TABLE.md`): `°C/мин` и `Гр/мин` между собой не мостятся,")
    a("   а `Da`, `Pe`, `Bi`, `κ` — мостятся.")
    a("4. **Единственное наше собственное безразмерное число, которое не подтвердилось** — сдвиг порога")
    a("   `√(2 ln N)` (`FINDING-339`). Это тем важнее, что остальные пять — из работ, а не наши.")
    a("")
    a("## Чего в таблице нет")
    a("")
    a("- **Ни одного числа, где порог измерен в двух системах одинаково.** Био = 0,238 — одно значение;")
    a("  Дамкёлер = 1 — из моделей, а не из живого объекта.")
    a("- **Числа Рейнольдса, Мортона, Фурье** и других классических — не включены: в наших ячейках их нет.")
    a("- **Не показано, какой режим «лучше»**: таблица переключает описание, а не ценность.")

    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
