"""Что следует из измеренного интервала критической скорости (глиома C6).

Данные DIP41-0001: сдвиг 300 -> 440 мосмоль/кг (превышение 140).
При 3 мосмоль/(кг·мин) = 180 в час объём держится; при 6 (360 в час) и 9 (540 в час) падает.

Формула: (L/L*) + (v/v*)^2 <= 1.

Скрипт считает допустимые комбинации (L/L*, v*) и предсказание для проверки. Только арифметика.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CHECK-C6.md"

LEVEL = 140.0          # мосмоль/кг превышение
V_HOLD = 180.0         # в час, объём держится
V_FAIL = 360.0         # в час, объём падает


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Что следует из ряда скоростей в глиоме C6")
    a("")
    a("Сгенерировано `tools/check_c6.py`. Данные: `DIP41-0001`, формула `I-039`.")
    a("")
    a(f"Условия: превышение {LEVEL:.0f} мосмоль/кг; {V_HOLD:.0f} в час — держится, {V_FAIL:.0f} — падает.")
    a("")
    a("## Какие v* совместимы с обоими наблюдениями")
    a("")
    a("Обозначим X = L/L*. Тогда:")
    a("")
    a(f"    держится:  X + ({V_HOLD:.0f}/v*)^2 <= 1")
    a(f"    падает:    X + ({V_FAIL:.0f}/v*)^2 > 1")
    a("")
    a("| v*, в час | какой должна быть доля уровня X |")
    a("|---|---|")
    rows = []
    for vstar in (180, 220, 250, 300, 360, 450):
        x_max = 1 - (V_HOLD / vstar) ** 2
        x_min = 1 - (V_FAIL / vstar) ** 2
        rows.append((vstar, x_max, x_min))
        a(f"| {vstar} | от {max(0.0, x_min):.2f} до {x_max:.2f} |")
    a("")
    a("Что видно: при реалистичных v* (250-300 в час) доля уровня, при которой система ещё держится,")
    a("составляет меньше половины критической. То есть **в этом опыте решает темп, а не уровень**:")
    a("клетки гибнут, не доходя до порога по нагрузке.")
    a("")
    a("## Проверяемое следствие")
    a("")
    a("Если формула верна, то при скорости 180 мосмоль/кг в час (которая держит) система должна сорваться,")
    a("когда конечный уровень вырастет примерно вдвое-втрое. Проверка: повторить опыт при 180 в час с")
    a("конечными уровнями 440, 660, 880 мосмоль/кг и найти точку срыва. Она должна попасть в интервал,")
    a("предсказанный строкой для выбранного v*.")
    a("")
    a("## Обратное следствие")
    a("")
    a("Если при 180 в час срыв наступает **сразу** при небольшом росте уровня, значит квадрат на темпе")
    a("слишком силён (надо первую степень). Если не наступает даже при утроении — слишком слаб.")
    a("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
