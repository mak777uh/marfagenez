"""κ из PAL: `κ ≈ 1/PAL` — проверяемое числовое соответствие, а не совпадение слов.

Что известно из карты (`DIP56-0005`, DLW-база, североевропейская выборка):
    PAL = 1,70 ± 0,23 (женщины, n = 301)   1,77 ± 0,28 (мужчины, n = 346)

Наше κ (доля потока на поддержание) в записи `F-005`/`F-021` фигурирует как 0,57.

Проверяется: совпадает ли `1/PAL` с 0,57 с учётом разброса PAL, и насколько это чувствительно к
интерпретации PAL.

PAL (physical activity level) = TEE / BMR, поэтому доля поддержания по отношению к расходу:
    BMR / TEE = 1 / PAL
Это и есть κ в смысле «доля ресурса на поддержание сомы».

Запуск: python3 tools/kappa_pal.py
"""

from __future__ import annotations


def main() -> int:
    kappa_recorded = 0.57
    groups = [
        ("женщины", 1.70, 0.23, 301),
        ("мужчины", 1.77, 0.28, 346),
    ]

    print("== κ = 1/PAL из DLW-базы (DIP56-0005)")
    print(f"{'группа':>10} {'PAL':>6} {'SD':>5} {'1/PAL':>7} {'интервал ±1 SD':>20}")
    for name, pal, sd, n in groups:
        inv = 1.0 / pal
        lo, hi = 1.0 / (pal + sd), 1.0 / (pal - sd)
        print(f"{name:>10} {pal:>6.2f} {sd:>5.2f} {inv:>7.3f} {f'{lo:.3f}–{hi:.3f}':>20}")

    print()
    print(f"== сравнение с записанным κ = {kappa_recorded}")
    inside = []
    for name, pal, sd, _ in groups:
        lo, hi = 1.0 / (pal + sd), 1.0 / (pal - sd)
        ok = lo <= kappa_recorded <= hi
        inside.append(ok)
        print(f"  {name}: 1/PAL ∈ [{lo:.3f}, {hi:.3f}] -> κ = {kappa_recorded} "
              f"{'попадает' if ok else 'НЕ попадает'}")

    print()
    print("== то же по BMR/TEE напрямую (вторая, независимая формулировка)")
    print("  BMR/TEE ≈ 0,57 по обзорам энергетики человека — совпадает с 1/PAL при PAL ≈ 1,75")
    print(f"  1/1,75 = {1/1.75:.3f}")

    print()
    print("== пределы и чувствительность")
    for pal in (1.4, 1.6, 1.75, 2.0, 2.5):
        print(f"  PAL = {pal:.2f} -> κ = {1/pal:.3f}")

    print()
    print("== что это НЕ доказывает")
    print("  PAL — интегральный показатель за недели, κ — мгновенная доля потока: соответствие верно")
    print("  как СРЕДНЕЕ, а не как равенство в каждый момент.")
    print("  И κ = 0,57 — наша запись, а не независимое измерение: совпадение подтверждает согласованность")
    print("  двух наших величин, а не истинность κ.")
    return 0 if all(inside) else 1


if __name__ == "__main__":
    raise SystemExit(main())
