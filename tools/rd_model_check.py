"""Проверка конкурирующей модели RD (атом FAST-P3-01) на данных RIF: даёт ли она 5-кратное замедление?

Модель RD (дрожжи, PFGE, Table 1 из 10.1371/journal.pone.0146407):
    dDSB1/dt = k1·R − (v1 + q1·R)·DSB1
    dDSB2/dt = k2·R − (v2 + q2·R)·DSB2 + q1·R·DSB1
    dDSB3/dt = k3·R + q2·R·DSB2
с параметрами v1 = 1,07 ч⁻¹, v2 = 4,44·10⁻² ч⁻¹, q1 = 1,22·10⁻³ Гр⁻¹, q2 = 2,67·10⁻⁴ Гр⁻¹.

Наблюдение (W4-0033, MCF10A): эффективный период разрешения RIF 1,4 ч при 0,1 Гр и 5,7 ч при 2 Гр —
то есть видимое замедление в 4,1 раза по t½ (5,7/1,4).

Что считается здесь: после острого облучения при фиксированной мощности дозы берётся состав классов и
эффективная скорость потери DSB (взвешенная по классам: v1 для DSB1, v2 для DSB2, 0 для DSB3), из неё —
t½_eff. Сравнивается отношение t½_eff(2 Гр)/t½_eff(0,1 Гр) с наблюдённым 4,1.

Оговорка: параметры — для дрожжей и PFGE-разрывов, а данные — фокусы в клетках человека. Тест
показывает, может ли эта форма дать нужное замедление **по порядку величины**, а не точное согласие.

Запуск: python3 tools/rd_model_check.py
"""

from __future__ import annotations

import math

V1, V2 = 1.07, 4.44e-2
Q1, Q2 = 1.22e-3, 2.67e-4
K1 = K2 = K3 = 30.0     # выход DSB на Гр (Mori 2018: ~30 DSB/(Гр·клетка))


def simulate(dose: float, rate: float, dt: float = 1e-4) -> tuple[float, float]:
    """Возвращает (DSB1, DSB2) сразу после облучения. rate — Гр/ч."""
    t_total = dose / rate
    y = [0.0, 0.0]
    t = 0.0
    while t < t_total:
        h = min(dt, t_total - t)
        d1, d2 = y
        a1 = K1 * rate - (V1 + Q1 * rate) * d1
        a2 = K2 * rate - (V2 + Q2 * rate) * d2 + Q1 * rate * d1
        y = [d1 + h * a1, d2 + h * a2]
        t += h
    return y[0], y[1]


def t_half_eff(dose: float, rate: float) -> float:
    d1, d2 = simulate(dose, rate)
    d3_share = 0.0
    total = d1 + d2
    if total <= 0:
        return float("nan")
    v_eff = (V1 * d1 + V2 * d2) / total
    return math.log(2) / v_eff


def main() -> int:
    print("== RD-модель: эффективный t½ после острого облучения")
    for rate in (60.0, 120.0, 240.0):
        t1 = t_half_eff(0.1, rate)
        t2 = t_half_eff(2.0, rate)
        print(f"  мощность {rate:>6.0f} Гр/ч: t½(0,1 Гр) = {t1:.3f} ч, t½(2 Гр) = {t2:.3f} ч, "
              f"отношение = {t2/t1:.2f}")

    obs = 5.7 / 1.4
    print()
    print(f"  наблюдение (RIF, MCF10A): t½ 1,4 -> 5,7 ч, отношение {obs:.2f}")
    t1 = t_half_eff(0.1, 120.0)
    t2 = t_half_eff(2.0, 120.0)
    ratio = t2 / t1
    print(f"  RD при 120 Гр/ч даёт отношение {ratio:.2f}")
    print()
    if ratio < 1.5:
        print("ВЫВОД: RD-модель с записанными параметрами НЕ объясняет наблюдённое замедление.")
        print("        Причина: конверсия q·R мала при больших мощностях, класс DSB3 набирается медленно,")
        print("        поэтому видимая скорость почти не меняется. Значит RD и v3 объясняют разные данные,")
        print("        и ни одна из форм не описывает оба эндпоинта — это напряжение, а не согласие.")
        return 1
    print("ВЫВОД: RD-модель даёт замедление того же порядка — она конкурирует с v3 на данных RIF.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
