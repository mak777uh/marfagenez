"""Фаза 2.4: «растворение» — второй тип порога, не по накопленному и не по темпу.

Своя конструкция, помечено. Опора — принятые ячейки карты о мембране и её цене.

Запуск: python3 tools/dissolution.py [--write]
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "FORMULA-DISSOLUTION.md"

# опоры из карты: (ячейка, что даёт)
SUPPORT = [
    ("DIP12-0009", "цена проницаемости задана знаком энтальпийного и энтропийного вкладов"),
    ("DIP12-0005", "натяжение само вызывает рост (положительная обратная связь)"),
    ("B22-01-0001", "порог накопленного изменения 5 МПа"),
    ("DIP42-0008", "деление везикулы по порогу площади"),
    ("DIP16-0006", "порог отношения осмолярностей не зависит от размера"),
]


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# «Растворение»: порог, при котором граница перестаёт быть границей")
    a("")
    a("**Это моя конструкция**, не формула из источника. Опора — принятые ячейки карты; проверить её пока "
      "нечем, и это записано ниже.")
    a("")
    a("## Зачем нужен третий тип порога")
    a("")
    a("У нас уже есть два типа:")
    a("")
    a("| тип | что копится | пример |")
    a("|---|---|---|")
    a("| по накопленному | повреждение/давление | **5 МПа** (`B22-01-0001`) |")
    a("| по темпу | скорость подачи | **187 °C/мин**, **3 мОсм/мин** |")
    a("| **по границе (этот)** | потеря самой границы | ниже |")
    a("")
    a("Первые два отвечают на вопрос «сколько вытерпит». Третий — на другой: **когда система перестаёт быть "
      "отдельной системой**, даже если её «внутренние» переменные ещё в норме.")
    a("")
    a("## Запись")
    a("")
    a("```")
    a("граница держится, если:  σ(цена границы) ≤ доход на поддержание границы")
    a("растворение наступает при:  c_skin(t) = ∂V/∂b → предельная цена удержания превышает доход")
    a("после растворения:  переменные «внутри» не определены — обмен становится свободным")
    a("```")
    a("")
    a("`c_skin` — теневая цена удержания границы (это наша `C-001`/`F-023`, не выдумка); `b` — ресурс "
      "границы; `V` — оптимизированный потенциал.")
    a("")
    a("## Чем это отличается от двух других порогов")
    a("")
    a("1. **Не по накопленному:** накопленное повреждение может быть малым, а граница уже не окупается — "
      "если выросла её цена (например, среда стала враждебной).")
    a("2. **Не по темпу:** растворение не требует быстрого изменения — достаточно, чтобы цена удержания "
      "перевалила доход.")
    a("3. **Необратимость другая:** после перехода «внутри» перестаёт быть определённым. Поэтому это не "
      "смерть системы, а **потеря индивидуальности** — в терминах карты, переход от «слона» к «пятну».")
    a("")
    a("## Опора из карты")
    a("")
    a("| ячейка | что даёт |")
    a("|---|---|")
    for cid, what in SUPPORT:
        a(f"| `{cid}` | {what} |")
    a("")
    a("## Что предсказывает")
    a("")
    a("1. **Скачок, а не полюс.** Цена удержания кусочно-постоянна (`F-023`, изломы цены), значит переход "
      "происходит при пересечении порога, а не как расходимость.")
    a("2. **Порог сдвигается средой:** чем дороже удержание, тем меньше нужен урон для растворения. "
      "Это проверяемо: одна и та же мембрана в разных условиях растворяется при разном повреждении.")
    a("3. **Асимметрия:** обратный переход (собрать границу заново) требует **больше** ресурса, чем "
      "удержание, — иначе растворение было бы обратимым и наблюдалось бы как обычное повреждение.")
    a("")
    a("## Чем это опровергается")
    a("")
    a("- Если потеря границы всегда происходит **после** достижения порога по накопленному — третий тип "
      "не нужен, это тот же второй.")
    a("- Если после потери границы систему можно восстановить **тем же** количеством ресурса, что и "
      "удержать, — «необратимости» нет.")
    a("")
    a("## Чего не хватает")
    a("")
    a("- **Нет измерения `c_skin` в живом объекте.** Цена удержания у нас — из оптимизационной задачи, "
      "а не из измерения.")
    a("- Нет эксперимента, где граница теряется **при сохранных внутренних переменных**.")
    a("- Неясно, что считать «границей» в наших данных: мембрана, оболочка везикулы, кожный барьер — "
      "это разные объекты с разными числами.")

    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
