"""Пересчёт единиц скорости и проверка применимости закона Medina к клеточным рампам.

Все константы и формулы — из источника:
  Medina et al., mSphere, DOI 10.1128/msphere.00594-26, PMC13711787, Methods:
  Pi = (-R*T/Vw) * ln(aw),  R = 8.314 J/(mol*K), T = 298 K, Vw = 18.015e-6 m^3/mol, Pi в МПа.
  Table 1: log10(C/C0) = beta * (dPi/dt), beta = -0.030 (E. coli), -0.011 (S. epidermidis),
  единицы скорости — МПа за 5 минут.

Скрипт ничего не моделирует: он переводит опубликованные коэффициенты в общие единицы и
проверяет, что закон предсказывает при клеточных скоростях.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "UNITS-RATE.md"

R = 8.314          # Дж/(моль*К), из источника
T = 298.0          # К, из источника
VW = 18.015e-6     # м^3/моль, из источника
BETA_ECOLI = -0.030
BETA_STAPH = -0.011
WINDOW_MIN = 5.0   # единица скорости в источнике — МПа за 5 минут

# 1 осмоль/кг по идеальному закону Вант-Гоффа: Pi = c*R*T при c = 1000 моль/м^3
MPA_PER_OSMOL = 1000.0 * R * T / 1e6      # МПа на 1 осмоль/кг
OSMOL_PER_MPA = 1.0 / MPA_PER_OSMOL

# Скорости из принятых ячеек (в исходных единицах источника)
CELL_RATES_MPA_PER_MIN = {
    "почка мыши, рампа 50 мОсм/(кг·ч)": 50.0 * 1e-3 * MPA_PER_OSMOL / 60.0,
    "глиома C6, 180 мОсм/(кг·ч)": 180.0 * 1e-3 * MPA_PER_OSMOL / 60.0,
    "глиома C6, 360 мОсм/(кг·ч)": 360.0 * 1e-3 * MPA_PER_OSMOL / 60.0,
    "Jurkat, рампа 30 мОсм/(л·ч)": 30.0 * 1e-3 * MPA_PER_OSMOL / 60.0,
    "сушка капли, медленная (85,9 МПа за 5 мин)": 85.9 / WINDOW_MIN,
    "сушка капли, быстрая (118 МПа за 5 мин)": 118.0 / WINDOW_MIN,
}


def loss_log10(beta: float, rate_mpa_per_min: float) -> float:
    """log10(C/C0) по закону источника: beta * (Pi за 5 минут)."""
    return beta * rate_mpa_per_min * WINDOW_MIN


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Единицы скорости: пересчёт и границы применимости")
    a("")
    a("Сгенерировано `tools/units_rate.py`. Все константы — из `B21-01-0001` (Medina, mSphere,")
    a("PMC13711787, Methods) и `B22-01-0002` (там же, числа сушки).")
    a("")
    a("## Опубликованная формула пересчёта")
    a("")
    a("    Pi = (-R*T/Vw) * ln(aw)")
    a("")
    a(f"R = {R} Дж/(моль·К), T = {T} К, Vw = {VW:.3e} м³/моль, Pi в МПа.")
    a("")
    a("## Пересчёт единиц")
    a("")
    a(f"- 1 осмоль/кг по идеальному Вант-Гоффу = **{MPA_PER_OSMOL:.3f} МПа**;")
    a(f"- 1 МПа = **{OSMOL_PER_MPA * 1000:.1f} мОсм/кг**;")
    a(f"- скорость в единицах источника (МПа за 5 мин) × **{12.0:.0f}** = МПа/ч;")
    a("")
    a("## Что закон предсказывает при клеточных скоростях")
    a("")
    a("| система | скорость, МПа/мин | предсказанная потеря, log10 | доля выживших |")
    a("|---|---|---|---|")
    for name, rate in CELL_RATES_MPA_PER_MIN.items():
        lg = loss_log10(BETA_ECOLI, rate)
        surv = 10 ** lg
        a(f"| {name} | {rate:.4f} | {lg:.4f} | {surv * 100:.2f}% |")
    a("")
    a("## Чему это противоречит")
    a("")
    a("| система | измерено | предсказано законом Medina |")
    a("|---|---|---|")
    a("| почка мыши, 640→1640 за 20 ч | 89% выживших | практически 100% |")
    a("| глиома C6, 180 мОсм/(кг·ч) | деление держится | практически 100% |")
    a("| Jurkat, рампа 10 ч | 40% выживших | практически 100% |")
    a("")
    a("**Вывод: закон Medina не описывает клеточные рампы.** Он измерен в режиме, где скорость на")
    a("2–4 порядка выше: у него 17–24 МПа/мин, у клеточных рамп — 0,005–0,04 МПа/мин.")
    a("")
    a("## Какая скорость нужна, чтобы закон дал заметную потерю")
    a("")
    for target, label in ((-0.3, "50%"), (-1.0, "10%"), (-2.0, "1%")):
        rate = target / (BETA_ECOLI * WINDOW_MIN)
        a(f"- до {label} выживших: **{rate:.2f} МПа/мин** = "
          f"{rate * 60 / MPA_PER_OSMOL * 1000:.0f} мОсм/(кг·ч)")
    a("")
    a("## Что это значит для формулы")
    a("")
    a("1. Пересчёт единиц **есть**, он опубликован, и он обратим: МПа ↔ мОсм/кг через R·T.")
    a("2. Но коэффициент `beta` **нельзя переносить** из режима сушки в режим клеточных рамп:")
    a("   там разные диапазоны скоростей, и закон в клеточном диапазоне даёт почти нулевую потерю")
    a("   при измеренной потере в десятки процентов.")
    a("3. Значит **закон режимно-специфичен** — это подтверждает `I-054` (скорость входит внутрь")
    a("   параметра поля, а не отдельным универсальным регрессором).")
    a("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
