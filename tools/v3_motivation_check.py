"""Значима ли «инверсия», ради которой введена v3?

v3 (`R(D) = C0·exp(−D/a)·(1 + D/b)`) появилась потому, что у 53BP1-фокусов при большей дозе
разрешение оказалось БЫСТРЕЕ: `t½ = 3,1 ± 0,5 ч` при 5–10 мГр против `2,7 ± 0,8 ч` при 500 мГр
(`DIP59-0006`). Это единственное наблюдение, требующее НЕмонотонности.

Здесь проверяется, значимо ли это различие статистически. Если нет — «инверсия» может быть шумом, и
немонотонность v3 не имеет основания в данных (а её два свободных параметра подгоняются под две точки,
что почти всегда удаётся).

Запуск: python3 tools/v3_motivation_check.py
"""

from __future__ import annotations

import math


def diff_z(mean1: float, sd1: float, mean2: float, sd2: float) -> tuple[float, float]:
    """z и двусторонний p для разности средних (без предположения равенства дисперсий)."""
    se = math.sqrt(sd1 ** 2 + sd2 ** 2)
    z = abs(mean1 - mean2) / se
    p = math.erfc(z / math.sqrt(2))
    return z, p


def main() -> int:
    print("== 53BP1-фокусы (DIP59-0006): t½ при 5–10 мГр против 500 мГр")
    m1, s1 = 3.1, 0.5      # 5–10 мГр
    m2, s2 = 2.7, 0.8      # 500 мГр
    z, p = diff_z(m1, s1, m2, s2)
    print(f"  t½ = {m1} ± {s1} ч против {m2} ± {s2} ч")
    print(f"  разность = {m1 - m2:.1f} ч;  z = {z:.2f};  p = {p:.3f}")
    print(f"  вывод: {'значимо' if p < 0.05 else 'НЕ значимо'} на уровне 5 %")

    print()
    print("== RIF-фокусы (W4-0033): 1,4 ч при 0,1 Гр против 5,7 ч при 2 Гр")
    m3, s3 = 1.4, 0.2      # погрешность не записана в атоме; берём консервативные 0,2 ч
    m4, s4 = 5.7, 0.6
    z2, p2 = diff_z(m3, s3, m4, s4)
    print(f"  t½ = {m3} ± {s3} ч против {m4} ± {s4} ч (оценка погрешностей)")
    print(f"  разность = {m4 - m3:.1f} ч;  z = {z2:.2f};  p = {p2:.3g}")
    print(f"  вывод: {'значимо' if p2 < 0.05 else 'НЕ значимо'} — и по порядку величины видно, что да")

    print()
    print("== что это значит для v3")
    if p >= 0.05:
        print("  Единственное наблюдение, требующее немонотонности, статистически НЕ значимо.")
        print("  Значит v3 опирается не на данные, а на шум: её лишний параметр `b` подгоняется под")
        print("  различие в 0,4 ч при погрешностях 0,5 и 0,8 ч.")
        print("  Монотонная v2 объясняет те же данные не хуже, если учесть погрешности.")
        return 1
    print("  Инверсия значима — v3 имеет основание в данных.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
