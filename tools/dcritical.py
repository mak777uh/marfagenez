"""Точка невозврата: два порога вместо одного.

Это **моя конструкция** (разрешено: свои формулы как часть исследования), собранная из принятых ячеек
карты. Она не подгоняется под данные: числа ниже — иллюстрация структуры, а не измерение.

Опоры:
  B21-01-0003  выход цитохрома c не выключает биоэнергетику (повреждение ≠ смерть)
  B21-01-0004  анастасис: >90% клеток восстанавливаются после снятия индуктора
  B22-01-0006  ни пик, ни скорость, ни сумма каспазы не предсказывают исход по отдельности
  DIP49-0001/0002  быстрая (18-36 мин) и медленная (1,5-5,1 ч) компоненты репарации ДНК
  DIP49-0006   вырезание 8-oxoG: полураспад 11 мин (k ≈ 3,78 ч^-1)
  DIP49-0010   аутофагосомы 54/ч базально
  I-060        пропускная способность ремонта различается по этапам в 40-60 раз внутри класса

Формула (своя):
    dD/dt = P − C(D),        C(D) = C0 · exp(−D / D_cap)
    точка невозврата:        D_crit = D_cap · ln(C0 / P_0)
    смерть:                  D_death > D_crit  (отдельное событие, не тот же порог)

Запуск: python3 tools/dcritical.py [--write]
"""

from __future__ import annotations

import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "FORMULA-DCRITICAL.md"

# примерные пропускные способности из ячеек, 1/ч (для иллюстрации масштаба, не для подгонки)
C0_EXAMPLES = [
    ("быстрая репарация ДНК (DIP49-0001)", 1.14, 2.31),
    ("медленная репарация ДНК (DIP49-0002)", 0.14, 0.46),
    ("вырезание 8-oxoG (DIP49-0006)", 3.78, 3.78),
    ("обновление белков, культура (DIP49-0007)", 0.035, 0.05),
]

# отношения «пропускная способность / поток повреждения» — ось, по которой двигается точка невозврата
RATIOS = [1.2, 2.0, 5.0, 10.0, 100.0]


def dcrit(ratio: float) -> float:
    """D_crit / D_cap = ln(C0/P)."""
    return math.log(ratio)


def main(argv: list[str]) -> int:
    lines: list[str] = []
    a = lines.append
    a("# Формула точки невозврата: два порога вместо одного")
    a("")
    a("**Это моя конструкция**, а не формула из источника. Собрана из принятых ячеек карты; числа ниже — "
      "иллюстрация структуры, а не измерение. Сгенерировано `tools/dcritical.py`.")
    a("")
    a("## Запись")
    a("")
    a("```")
    a("dD/dt = P − C(D),   C(D) = C0·exp(−D/D_cap)")
    a("")
    a("точка невозврата:  D_crit = D_cap·ln(C0/P0)")
    a("смерть:            D_death > D_crit   (отдельное событие, а не тот же порог)")
    a("```")
    a("")
    a("`D` — повреждение в единицах «событий, эквивалентных одному ремонту»; `P` — поток повреждения "
      "(событий в час); `C0` — пропускная способность ремонта (событий в час); `D_cap` — повреждение, при "
      "котором способность ремонта падает в `e` раз (событий).")
    a("")
    a("## Почему два порога, а не один")
    a("")
    a("Если повреждение только копится, порог один — «сколько вытерпит». Но повреждение, по ячейкам карты, "
      "**снижает саму способность ремонта**: после выхода цитохрома c биоэнергетика не выключается "
      "(`B21-01-0003`), клетки восстанавливаются после снятия индуктора (`B21-01-0004`), а предсказать "
      "исход по одному числу нельзя (`B22-01-0006`). Отсюда два разных порога:")
    a("")
    a("- **`D_crit`** — выше него система ещё жива, но восстановиться уже не может (ремонт слабее потока);")
    a("- **`D_death`** — выше него наступает гибель; **`D_death > D_crit`**.")
    a("")
    a("## Как двигается точка невозврата")
    a("")
    a("Всё задаёт **отношение** `C0/P0`, а не абсолютные величины:")
    a("")
    a("| `C0/P0` | `D_crit / D_cap` | что это значит |")
    a("|---|---|---|")
    for r in RATIOS:
        note = "поток почти равен ремонту: порог очень низкий" if r < 1.5 else (
            "запас есть, но небольшой" if r < 5 else "ремонт с большим запасом")
        a(f"| {r:g} | {dcrit(r):.2f} | {note} |")
    a("")
    a("**Ключевое следствие:** порог растёт как **логарифм** отношения, то есть каждое удвоение запаса "
      "ремонта добавляет `ln 2 = 0.69·D_cap` — одну и ту же величину, а не пропорциональную.")
    a("")
    a("## Масштаб пропускной способности по ячейкам")
    a("")
    a("| этап | `C0`, 1/ч | сколько это |")
    a("|---|---|---|")
    for name, lo, hi in C0_EXAMPLES:
        rng = f"{lo:g}" if lo == hi else f"{lo:g}–{hi:g}"
        a(f"| {name} | {rng} | |")
    a("")
    a("Разброс между этапами — **два порядка** (0,035 у белков против 3,78 у 8-oxoG), и это согласуется с "
      "`I-060`: внутри одного класса повреждений репарация различается в 40–60 раз. Значит `D_crit` в одной "
      "и той же клетке **разный для разных видов повреждения** — единого порога нет.")
    a("")
    a("## Область применимости (найдено аудитом `tools/formula_audit.py`)")
    a("")
    a("Формула записана для `P0 < C0`, и это **не оговорка, а условие существования** стационарного")
    a("состояния. За пределами условия запись ведёт себя неправильно, и это проверено численно:")
    a("")
    a("| случай | что даёт формула | что должно быть |")
    a("|---|---|---|")
    a("| `P0 > C0` | **отрицательный** порог | стационарного состояния нет: поток превышает ремонт, "
      "величина не определена |")
    a("| `P0 → 0` | порог уходит в **бесконечность** | нужен нижний предел потока (фоновое повреждение) |")
    a("| `P0 = C0` | порог `= 0` | верно: запаса нет, первое повреждение необратимо |")
    a("")
    a("Значит формула — **локальная**, а не всеобщая: она отвечает на вопрос «где точка невозврата», пока")
    a("ремонт сильнее потока. При обратном неравенстве вопрос теряет смысл и надо говорить о распаде, а не")
    a("о пороге.")
    a("")
    a("## Что это предсказывает (и как проверить)")
    a("")
    a("1. **Порог зависит от запаса ремонта логарифмически.** Проверка: подать импульс повреждения разной "
      "величины, снять индуктор и найти границу восстановления; повторить при подавлении ремонта "
      "(например, OGG1 или протеасомы). Предсказание: граница сдвигается на `ln(C0/C0')·D_cap`.")
    a("2. **`D_crit < D_death`.** Проверка: в одной системе измерить обе границы — восстановление после "
      "снятия индуктора и гибель — и показать, что между ними есть полоса «жив, но не восстановится».")
    a("3. **Порог зависит от вида повреждения** внутри одной клетки: у 8-oxoG он выше, чем у белков, при "
      "одинаковом `D_cap`.")
    a("")
    a("## Чем это опровергается")
    a("")
    a("- Если `D_crit` **не зависит** от пропускной способности ремонта — член `C(D)` неверен, и порог "
      "описывается одним накоплением.")
    a("- Если `D_crit` **совпадает** с `D_death` во всех измерениях — двухпороговая структура лишняя.")
    a("- Если после снятия индуктора восстановление идёт **полностью при любом** накопленном повреждении — "
      "точки невозврата нет вовсе (анастасис без границы).")
    a("")
    a("## Чего не хватает")
    a("")
    a("- **`D_cap` не измерен ни в одной системе.** Это ключевая величина: без неё формула задаёт только "
      "форму зависимости, но не числа.")
    a("- Нет работы, где `D_crit` и `D_death` измерены **в одной системе**.")
    a("- Поток `P` в наших источниках задаётся внешне (мМ/мин, °C/мин, Гр/мин), а не в единицах ремонта.")

    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
