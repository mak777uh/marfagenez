"""Предсказание критической скорости из измеренных порогов.

Формула нашей конструкции:  (L/L*) + (v/v*)^2 <= 1.
Для проверки нужна величина v* в той же единице, что и L*.
Простейший вывод из уже принятых чисел: v* задаётся порогом, делённым на время обновления пула.

    v* = L* / tau

где tau — время полужизни пула (из DIP31-0001: 48,8 мин).

Скрипт только пересчитывает единицы из принятых ячеек и печатает предсказание.
Ничего не моделирует.

Usage: python3 tools/predict_two_axes.py [--write]
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "PREDICTION-TWO-AXES.md"

# принятые числа
KM_M = 6e-8            # DIP31-0005, М
HALF_LIFE_MIN = 48.8   # DIP31-0001, мин
R_CRIT_CYANO = 0.1378  # DIP34-0005, 1/сут
R_CRIT_PLANKTON = 0.003  # DIP34-0008, 1/сут


def main(argv: list[str]) -> int:
    tau_s = HALF_LIFE_MIN * 60.0
    v_star_M_s = KM_M / tau_s
    v_star_M_day = v_star_M_s * 86400.0
    v_star_per_day_if_M = v_star_M_day  # при L* = 1 М; для L* = Km — см. ниже

    lines: list[str] = []
    a = lines.append
    a("# Предсказание: какая критическая скорость следует из измеренных порогов")
    a("")
    a("Сгенерировано `tools/predict_two_axes.py` из принятых ячеек. Скрипт только пересчитывает единицы.")
    a("")
    a("Формула: `(L/L*) + (v/v*)^2 <= 1` (`I-039`). Для проверки нужна `v*` в тех же единицах, что `L*`.")
    a("Вывод из принятых чисел: `v* = L* / tau`, где `tau` — время полужизни пула.")
    a("")
    a("## Числа")
    a("")
    a("| величина | значение | источник |")
    a("|---|---|---|")
    a(f"| L* (Km деградации) | {KM_M:.2e} М | `DIP31-0005` |")
    a(f"| tau (полужизнь клиренса) | {HALF_LIFE_MIN:.1f} мин = {tau_s:.0f} с | `DIP31-0001` |")
    a(f"| v* = L*/tau | {v_star_M_s:.2e} М/с | расчёт |")
    a(f"| v* = L*/tau | {v_star_M_day:.2e} М/сут | расчёт |")
    a(f"| измеренная r_crit у цианобактерий | {R_CRIT_CYANO} 1/сут | `DIP34-0005` |")
    a(f"| измеренная r_crit у планктона | {R_CRIT_PLANKTON} 1/сут | `DIP34-0008` |")
    a("")
    a("## Сравнение")
    a("")
    ratio = v_star_M_day / R_CRIT_CYANO
    a(f"Чтобы измеренная критическая скорость цианобактерий ({R_CRIT_CYANO} 1/сут) соответствовала расчётной "
      f"({v_star_M_day:.2e} М/сут), критическая нагрузка должна быть:")
    a("")
    a(f"    L* = v*_измеренная * tau = {R_CRIT_CYANO} * {tau_s:.0f} с = "
      f"{R_CRIT_CYANO / 86400.0 * tau_s:.2e} в единицах относительной нагрузки")
    a("")
    a("То есть если формула верна, система с полужизнью пула 48,8 мин и измеренной критической скоростью "
      f"{R_CRIT_CYANO} 1/сут должна обрываться при относительной нагрузке около "
      f"{(R_CRIT_CYANO / 86400.0 * tau_s) * 100:.1f}% от критической за сутки накопления.")
    a("")
    a("## Что это предсказывает в проверяемой форме")
    a("")
    a("| уровень нагрузки L/L* | предсказание для медленного подхода | для быстрого |")
    a("|---|---|---|")
    for frac in (0.1, 0.25, 0.5, 0.75):
        v_allowed = ((1 - frac) ** 0.5)
        a(f"| {frac:.2f} | выдерживает скорость до {v_allowed:.2f}·v* | срыв задолго до порога по уровню |")
    a("")
    a("## Чем это проверяется")
    a("")
    a("Нужны три числа в одной системе: `L*`, `tau` и хотя бы одна измеренная критическая скорость. "
      "Если предсказанная `v*` совпадёт с измеренной в пределах фактора два — форма верна; "
      "если разойдётся на порядок — член `v/v*` надо переписать (например, в первой степени).")
    a("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
