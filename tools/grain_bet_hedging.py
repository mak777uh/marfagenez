"""`F-026`: зерно среды задаёт тип bet-hedging — проверка различимости.

Утверждение: при **крупном зерне** приспособленность накапливается **мультипликативно** → выигрывает
консервативная стратегия (меньше дисперсии); при **мелком зерне** — аддитивно → дисперсия не наказывается.

Чтобы сравнение было корректным, стратегии задаются так, чтобы **среднее арифметическое совпадало**:
`W = exp(σ·z − σ²/2)`, `z ~ N(0,1)`. Тогда

- `E[W] = 1` для любого `σ` — мелкое зерно не различает стратегии по среднему;
- `E[log W] = −σ²/2` — крупное зерно наказывает дисперсию ровно на эту величину.

**История проверки:** первая версия считала `E[log(1+σz)]` с усечением и перенормировкой, и при `σ = 1,22`
усечение съедало половину массы — результат показывал, что большая дисперсия ВЫИГРЫВАЕТ. Это был артефакт
перенормировки, а не свойство модели. Логнормальная форма снимает вопрос: среднее сохраняется точно.

Опровергающее условие: если при одинаковом среднем крупное зерно не наказывает дисперсию (`E log W` не
убывает по `σ`), узел неверен.

Запуск: python3 tools/grain_bet_hedging.py
"""

from __future__ import annotations


def main() -> int:
    print("Стратегии с одинаковым средним E[W] = 1 и разной дисперсией")
    print(f"{'σ':>6} {'v = σ²':>8} {'крупное: E log W':>18} {'мелкое: E W':>12}")
    rows = []
    for sigma in (0.0, 0.25, 0.5, 1.0, 1.5, 2.0):
        v = sigma * sigma
        coarse = -v / 2.0          # E[log W] для W = exp(σz − σ²/2)
        fine = 1.0                 # E[W] = 1 по построению
        rows.append((sigma, v, coarse, fine))
        print(f"{sigma:6.2f} {v:8.3f} {coarse:18.6f} {fine:12.6f}")

    print()
    order = sorted(rows, key=lambda r: -r[2])
    print("порядок по крупному зерну (лучший первый): σ =", [r[0] for r in order])
    print("порядок по мелкому зерну: все равны (E W = 1)")

    print()
    print("ЧТО ЭТО ЗНАЧИТ:")
    print("  крупное зерно: E log W = −σ²/2 — выигрывает минимальная дисперсия (σ = 0, консервативная);")
    print("  мелкое зерно: E W = 1 у всех — по среднему стратегии неразличимы,")
    print("  поэтому решает не среднее, а риск разорения (форма распределения).")
    print()
    ok = order[0][0] == 0.0 and all(rows[i][2] >= rows[i + 1][2] for i in range(len(rows) - 1))
    if ok:
        print("ВЫВОД: различие подтверждено — крупное зерно монотонно наказывает дисперсию,")
        print("        мелкое зерно по среднему не различает стратегии.")
        return 0
    print("ВЫВОД: монотонности нет — узел неверен.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
