"""Порог ошибок Эйгена: единицы, пределы и численная согласованность двух записей.

В карте две записи об одном:

    F-007   σ · q^ν = 1        граница удержания информации, L_max ≈ ln(σ)/(1 − q)
    F-017   σ · q^ν > 1        порог;  μ_c = ln σ / ν

Проверяется: (1) безразмерность всех величин; (2) согласованность двух форм — из
`σ·q^ν = 1` следует `ν ≈ ln σ / (−ln q) ≈ ln σ/(1 − q)`, то есть `L_max ≈ ν`, а не
независимая величина; (3) пределы.

Запуск: python3 tools/eigen_threshold.py
"""

from __future__ import annotations

import math


def l_max_sigma(sigma: float, q: float) -> float:
    """Из σ·q^ν = 1:  ν = ln σ / (−ln q); при малом 1−q это ≈ ln σ/(1−q)."""
    return math.log(sigma) / -math.log(q)


def l_max_approx(sigma: float, q: float) -> float:
    return math.log(sigma) / (1 - q)


def main() -> int:
    print("== согласованность форм F-007 и F-017")
    print(f"{'σ':>4} {'q':>7} {'ν = lnσ/(−ln q)':>16} {'lnσ/(1−q)':>12} {'разница':>8}")
    for sigma, q in ((2.0, 0.999), (2.0, 0.99), (10.0, 0.9999), (1.5, 0.99999)):
        exact, approx = l_max_sigma(sigma, q), l_max_approx(sigma, q)
        print(f"{sigma:>4} {q:>7} {exact:>16.1f} {approx:>12.1f} {abs(exact-approx)/exact:>7.1%}")
    print()
    print("вывод: при q → 1 обе записи дают одно и то же; L_max — это ν, а не отдельная величина")

    print()
    print("== пределы")
    print("  q → 1      ⇒ −ln q → 0        ⇒ L_max → ∞   (идеальная репликация удерживает любой геном)")
    print("  σ → 1      ⇒ ln σ → 0         ⇒ L_max → 0   (нет превосходства — нечего удерживать)")
    print("  q^(ν) σ < 1 ⇒ порог нарушен   ⇒ ошибка катастрофы: информация не удерживается")
    print()
    print("== численная демонстрация: σ = 2")
    for q in (0.9999, 0.999, 0.99, 0.97):
        print(f"  q = {q}: L_max ≈ {l_max_sigma(2.0, q):8.1f} оснований; "
              f"{'удержимо' if l_max_sigma(2.0, q) > 100 else 'ниже типичного генома'}")
    print()
    print("== единицы (все безразмерные)")
    print("  σ   — превосходство (отношение приспособленностей), 1")
    print("  q   — точность копирования на основание (вероятность), 1")
    print("  ν   — длина генома в основаниях, 1 (счётная величина)")
    print("  L_max — та же длина, 1")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
