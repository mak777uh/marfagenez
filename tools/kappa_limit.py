"""`F-005` (правило κ): предел при `PAL → 1` и что стоит за «остатком».

Запись: `E = κ·E` на поддержание сомы `+ (1−κ)·E` на рост и размножение, `κ = 1/PAL`.

Пределы:
- `PAL → 1` (лежачий режим): `κ → 1`, остаток `1−κ → 0` — роста нет. Это согласуется со смыслом.
- `PAL` растёт: остаток растёт до 1 — «на рост и размножение» уходит почти вся энергия.

Проблема в подписи ветви, а не в арифметике: у взрослого человека остаток `1−κ` — это **активность**, роста
там почти нет. У клетки (AmP, `κ ≈ 0,9`) ветвь действительно про рост. Одна формула, две разные подписи.

Проверяем числами на данных карты: PAL 1,70–1,77 (средний взрослый), 3,40 (лыжницы), 4,37 (Giro).

Опровергающее условие: если при `PAL = 1` остаток не равен нулю, `κ = 1/PAL` несовместимо с записью.

Запуск: python3 tools/kappa_limit.py
"""

from __future__ import annotations


def main() -> int:
    rows = [
        ("средний взрослый (женщины, Westerterp)", 1.70, "активность"),
        ("средний взрослый (мужчины, Westerterp)", 1.77, "активность"),
        ("лыжницы-гонщицы (Park 2019)", 3.40, "активность"),
        ("профессиональные велогонщики, Giro (plateau)", 4.37, "активность"),
        ("лежачий режим (предел)", 1.00, "нет"),
        ("клетка, AmP (DEB)", 1.11, "рост"),
    ]
    print(f"{'группа':46} {'PAL':>6} {'κ = 1/PAL':>10} {'остаток 1−κ':>12}  что реально в остатке")
    worst_residual_at_one = None
    for name, pal, residual_kind in rows:
        kappa = 1.0 / pal
        rest = 1.0 - kappa
        print(f"{name:46} {pal:6.2f} {kappa:10.3f} {rest:12.3f}  {residual_kind}")
        if abs(pal - 1.0) < 1e-9:
            worst_residual_at_one = rest

    print()
    print("ЧТО ВИДНО:")
    print("  1. При PAL = 1 остаток РАВЕН НУЛЮ — предел согласуется с записью.")
    print("  2. У взрослого человека остаток 0,41–0,43 — это активность, а не рост: подпись ветви неверна.")
    print("  3. У гонщиков Giro остаток 0,77 — «на рост и размножение» 77 % энергии, чего не бывает.")
    print("  4. У клетки (AmP κ ≈ 0,9 → PAL ≈ 1,11) ветвь действительно про рост — там подпись верна.")
    print()
    print("ВЫВОД: арифметика `κ = 1/PAL` верна на всём диапазоне, но ОДНА подпись ветви не может обслуживать")
    print("        и клетку, и взрослого человека: у человека остаток — активность, у клетки — рост.")
    ok = worst_residual_at_one is not None and abs(worst_residual_at_one) < 1e-9
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
