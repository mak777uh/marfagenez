def main(argv: list[str]) -> int:
    atoms = [json.loads(l) for l in ATOMS.read_text(encoding="utf-8").splitlines() if l.strip()]
    ids = {a["atom"] for a in atoms}

    missing = [c for c, _, _ in PAIRS if c not in ids]
    if missing:
        print("нет ячеек:", missing)
        return 1

    kg_ids = set()
    nodes = [json.loads(l) for l in (ROOT / "kg" / "nodes.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    for n in nodes:
        kg_ids.add(n["id"])
    missing_kg = sorted({k for _, ks, _ in PAIRS for k in ks if k not in kg_ids})
    if missing_kg:
        print("нет узлов kg/:", missing_kg)
        return 1

    touched = 0
    for a in atoms:
        for cell, ks, _ in PAIRS:
            if a["atom"] == cell:
                a["kg_ref"] = list(dict.fromkeys((a.get("kg_ref") or []) + ks))
                touched += 1

    lit_refs = {}
    # 1) пары, заданные списком выше
    for cell, ks, why in PAIRS:
        for k in ks:
            lit_refs.setdefault(k, []).append(cell)
    # 2) пары, уже записанные в сами ячейки полем `kg_ref` (например, из внешних партий):
    #    иначе `lit-refs.json` знает только про список PAIRS и теряет их.
    for a in atoms:
        for k in a.get("kg_ref") or []:
            if a["atom"] not in lit_refs.setdefault(k, []):
                lit_refs[k].append(a["atom"])

    # 3) сохранить пары, внесённые другими механизмами (stitch_identity и т.п.):
    #    иначе перегенерация lit-refs.json теряет их — регрессия 2026-11-27 (F-008/F-009/F-010).
    if LITREFS.exists():
        old = json.loads(LITREFS.read_text(encoding="utf-8")).get("map", {})
        for k, cells in old.items():
            for c in cells:
                if c not in lit_refs.setdefault(k, []):
                    lit_refs[k].append(c)

    print(f"пар: {len(PAIRS)}, ячеек изменено: {touched}, узлов kg/ затронуто: {len(lit_refs)}")
    print()
    for cell, ks, why in PAIRS:
        print(f"  {cell} ↔ {', '.join(ks)}\n      {why}")

    if "--write" in argv:
        ATOMS.write_text("".join(json.dumps(a, ensure_ascii=False) + "\n" for a in atoms), encoding="utf-8")
        LITREFS.write_text(json.dumps({"version": 1, "note": "сшивка: узел kg/ -> ячейки литературной карты",
                                       "map": lit_refs}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"\nзаписано: {ATOMS.name}, {LITREFS.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
