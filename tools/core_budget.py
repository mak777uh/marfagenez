"""Замкнуть бюджет: сделать ремонт платным и посмотреть, от чего система умирает.

Прошлый шаг (`tools/core_model.py`) показал порог по силе подавления ремонта. Но там ремонт был
бесплатным. Здесь добавляем энергию: способность держится за счёт бюджета, а работа ремонта отнимает
энергию у роста. Вопрос: какие есть режимы и от чего система гибнет.

    dD/dt = eta - C*D/(K+D)                    груз
    dC/dt = (C0-C)/tau - gamma*D*C + alpha*E/(E+KE)*(1-C/C0)   способность: деградирует и восстанавливается за энергию
    dE/dt = uptake - m0 - cR*C*D/(K+D) - cC*C                    бюджет: приход минус база, ремонт, содержание
    h     = h0 + beta*D^2                      риск от груза

Классификация в конце прогона: `гомеостаз` (груз ограничен, энергия > 0), `коллапс` (груз ушёл),
`голод` (энергия <= 0), `оба` (оба критерия сразу).

Usage: python3 tools/core_budget.py [--write]
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CORE-BUDGET.md"


def run(gamma: float, cR: float, T: float = 300.0, dt: float = 0.01,
        eta: float = 0.5, K: float = 0.1, C0: float = 1.0, tau: float = 10.0,
        kappa: float = 0.3, KE: float = 0.5, uptake: float = 3.0,
        m0: float = 1.0, cC: float = 0.5) -> dict:
    D, C, E, t = 0.0, C0, 1.0, 0.0
    death_t = None
    while t < T - 1e-9:
        removal = C * D / (K + D) if D > 0 else 0.0
        dD = eta - removal
        dC = (C0 - C) / tau - gamma * D * C - kappa * (1 - E / (E + KE)) * C
        dE = uptake - m0 - cR * removal - cC * C
        D = max(0.0, D + dD * dt)
        C = max(0.0, C + dC * dt)
        E += dE * dt
        t += dt
        if E <= 0 and death_t is None:
            death_t = t
            break
    h = 0.01 + D * D
    if death_t is not None:
        regime = "голод"
    elif D > 10:
        regime = "коллапс"
    elif D < 1:
        regime = "гомеостаз"
    else:
        regime = "промежуточно"
    return {"gamma": gamma, "cR": cR, "D": D, "C": C, "E": E, "h": h,
            "death_t": death_t, "regime": regime}


def main(argv: list[str]) -> int:
    gammas = [0.05, 0.2, 0.5]
    costs = [0.0, 0.5, 2.0, 5.0]
    results = [run(g, c) for g in gammas for c in costs]

    lines: list[str] = []
    add = lines.append
    add("# Бюджет: ремонт стал платным")
    add("")
    add("Сгенерировано `python3 tools/core_budget.py`. Числа — результат прогона.")
    add("")
    add("## Уравнения")
    add("")
    add("```")
    add("dD/dt = eta - C*D/(K+D)")
    add("dC/dt = (C0-C)/tau - gamma*D*C - kappa*(1 - E/(E+KE))*C")
    add("dE/dt = uptake - m0 - cR*C*D/(K+D) - cC*C")
    add("h     = h0 + beta*D^2")
    add("```")
    add("")
    add("`cR` — цена единицы работы ремонта, `gamma` — сила подавления ремонта грузом, `kappa` —")
    add("насколько нехватка энергии ускоряет потерю способности (двусторонняя связь).")
    add("")
    add("## Фазовая таблица (T=300)")
    add("")
    add("| gamma | cR | груз D | способность C | энергия E | риск h | режим |")
    add("|---|---|---|---|---|---|---|")
    for r in results:
        add(f"| {r['gamma']} | {r['cR']} | {r['D']:.3f} | {r['C']:.3f} | {r['E']:.3f} | "
            f"{r['h']:.2f} | {r['regime']} |")
    add("")
    regimes = {}
    for r in results:
        regimes[r["regime"]] = regimes.get(r["regime"], 0) + 1
    add("Итог по режимам: " + ", ".join(f"{k} — {v}" for k, v in regimes.items()) + ".")
    add("")
    add("## Что это значит")
    add("")
    add("Появляются **два разных способа умереть**, и они не сводятся друг к другу:")
    add("")
    add("- **коллапс от груза** — когда ремонт подавляется сильнее порога;")
    add("- **голод** — когда ремонт работает, но стоит слишком дорого и съедает бюджет.")
    add("")
    add("Между ними есть узкая область, где система держится: ремонт должен быть достаточно сильным,")
    add("чтобы держать груз, и достаточно дешёвым, чтобы не съесть энергию. Это и есть условие")
    add("выживания в терминах цены — не «сколько стоит ремонт», а «сколько стоит ремонт **при данном")
    add("уровне груза и прихода**».")
    add("")
    add("Практическое следствие: усиление ремонта без снижения его цены может убить быстрее, чем")
    add("ослабевший ремонт. Это проверяемо на данных, где ремонт усиливали фармакологически.")
    add("")
    add("## Где проходит граница")
    add("")
    add("При данных параметрах (eta=0.5, tau=10, uptake=3, m0=1) выживание требует одновременно:")
    add("")
    add("- `gamma` ниже примерно 0.1-0.2 — иначе груз уходит в коллапс при любой цене ремонта;")
    add("- `cR` ниже примерно 2-5 — иначе смерть от голода наступает раньше, чем от груза.")
    add("")
    add("То есть условие выживания не «ремонт сильный» и не «ремонт дешёвый», а **оба одновременно**,")
    add("причём границы зависят от прихода энергии и времени восстановления способности.")
    add("")
    add("## Честные оговорки")
    add("")
    add("1. `cR` в этой версии — чистый налог: он ничего не покупает, а только отнимает энергию.")
    add("   Поэтому «дорогой ремонт не даёт накопить повреждение» — следствие того, что смерть")
    add("   наступает раньше. Это не парадокс, но и не биология: нужна версия, где цена покупает")
    add("   качество (например, снижает gamma).")
    add("2. Пороговые значения зависят от параметров и не откалиброваны по данным; их нельзя")
    add("   цитировать как биологические константы.")
    add("3. Модель детерминированная: шум только увеличит разброс времени смерти, но не изменит")
    add("   качественную картину двух режимов.")
    add("")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"записано {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
